"""Nine source tomography inputs generate the full F=1-to-33 channel.

The input basis is the retained bare F=1, m=-1,0,+1 inventory.  No caller
density or target effect is accepted.  Matrix-unit centres are linear
tomography reconstructions with trace-norm error bounds; CP is attributed to
the generated GKSL channel, rather than to the quantized centres.
"""
from fractions import Fraction as Q
import hashlib
from pathlib import Path

import atomic_dipole as dipole
import atomic_full_forward as full


BASIS = tuple(dipole.State("ground", 1, m) for m in (-1, 0, 1))
INDICES = tuple(dipole.INDEX[state] for state in BASIS)
PAIRS = ((0, 1), (0, 2), (1, 2))
NAMES = tuple("diag" + str(i) for i in range(3)) + tuple(
    name + str(i) + str(j) for i, j in PAIRS for name in ("plus", "plus_i"))


def initial_densities():
    result = [{(index, index): (Q(1), Q(0))} for index in INDICES]
    for i, j in PAIRS:
        a, b = INDICES[i], INDICES[j]
        result.extend(({(a, a): (Q(1, 2), Q(0)), (b, b): (Q(1, 2), Q(0)),
                        (a, b): (Q(1, 2), Q(0)), (b, a): (Q(1, 2), Q(0))},
                       {(a, a): (Q(1, 2), Q(0)), (b, b): (Q(1, 2), Q(0)),
                        (a, b): (Q(0), Q(-1, 2)), (b, a): (Q(0), Q(1, 2))}))
    return tuple(result)


def _inventories():
    return [{"name": name, "density": full._encode_density(matrix, 1)}
            for name, matrix in zip(NAMES, initial_densities())]


def _bindings():
    inherited = full._source_bindings()
    paths = (Path(full.__file__).resolve(), Path(__file__).resolve())
    return inherited + [{"path": str(path.relative_to(full.ROOT)),
                         "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
                        for path in paths if str(path.relative_to(full.ROOT)) not in
                        {item["path"] for item in inherited}]


def _controller(segments, bits, order, norm_cap, max_steps):
    if (type(segments) not in (tuple, list) or not segments
            or any(type(segment) is not full.Segment for segment in segments)):
        raise ValueError("nonempty primitive full33 Segment sequence required")
    if (type(bits) is not int or not 64 <= bits <= 1024 or type(order) is not int
            or not 16 <= order <= 256 or type(max_steps) is not int or max_steps < 1):
        raise ValueError("qutrit precision/order/step budget")
    cap = full.exact(norm_cap)
    if not 0 < cap <= 4:
        raise ValueError("qutrit Taylor cap")
    return cap


def _detector(d, eta):
    d, eta = full.exact(d), full.exact(eta)
    if not 0 <= d <= 1 or not 0 <= eta <= 1:
        raise ValueError("detector probabilities required")
    return d, eta


def _setup(segment, bits, order, quantum, cap):
    generator = full.Generator(segment, bits)
    if any((i == dipole.ION) != (j == dipole.ION) for i, j in generator.h_exact):
        raise ValueError("ion coherence generated by Hamiltonian")
    if any((i == dipole.ION) != (j == dipole.ION) for i, j, _, _ in generator.recycling):
        raise ValueError("ion coherence generated by recycling")
    ratio = segment.duration * generator.norm_bound / cap
    count = 0 if segment.duration == 0 else max(1, -(-ratio.numerator // ratio.denominator))
    dt = segment.duration / count if count else Q(0)
    step = full.step_certificate(generator, dt, quantum, order)
    record = {"raw_segment": segment.record(), "steps": count, "dt": str(dt),
              "liouvillian_entry_norm_bound": str(generator.norm_bound), **step,
              "generator_difference_bound": str(generator.generator_difference_bound),
              "angular_jump_certificates": generator.angular_jump_certificates,
              "natural_jump_count": generator.natural_jump_count,
              "ion_jump_count": generator.ion_jump_count,
              "ion_off_block_invariant": True}
    return generator, count, dt, record


def _advance_segment(generator, count, dt, states, errors, quantum, order, certificate):
    tail, rounding = Q(certificate["tail_factor"]), Q(certificate["rounding_error"])
    for _ in range(count):
        for index in range(9):
            errors[index] += full._entry_norm(states[index], quantum) * tail + rounding
            states[index] = full._advance(generator, states[index], dt, quantum, order)
            if any((i == dipole.ION) != (j == dipole.ION) for i, j in states[index]):
                raise ValueError("quantized ion off-block invariance failed")


def _linear(terms):
    result = {}
    for matrix, a, b in terms:
        for key, (real, imag) in matrix.items():
            full._add(result, key, a * real - b * imag, a * imag + b * real)
    return result


def _adjoint(matrix):
    return {(j, i): (real, -imag) for (i, j), (real, imag) in matrix.items()}


def _encoded_branch(matrix, error):
    return {"density_center": full._encode_density(matrix, 1),
            "trace_norm_error_upper": str(error)}


def _derive(states, errors, coefficients, quantum, d, eta):
    centers = [{key: (Q(real, quantum), Q(imag, quantum)) for key, (real, imag) in state.items()}
               for state in states]
    total_errors = [error + coefficients for error in errors]
    tomography, probabilities = {}, {}
    for name, matrix, error in zip(NAMES, centers, total_errors):
        probability = matrix.get((dipole.ION, dipole.ION), (Q(0), Q(0)))[0]
        raw = probability - error, probability + error
        physical = max(Q(0), raw[0]), min(Q(1), raw[1])
        if physical[0] > physical[1]:
            raise ValueError("qutrit ion probability intersection empty")
        trace = sum((real for (i, j), (real, _) in matrix.items() if i == j), Q(0))
        tomography[name] = {**_encoded_branch(matrix, error), "ionization_center": str(probability),
                            "ionization_raw_interval": list(map(str, raw)),
                            "ionization_interval": list(map(str, physical)),
                            "trace_interval": [str(trace - error), str(trace + error)]}
        probabilities[name] = physical
    units = {(i, i): centers[i] for i in range(3)}
    unit_errors = {(i, i): total_errors[i] for i in range(3)}
    for pair_index, (i, j) in enumerate(PAIRS):
        p, pi = 3 + 2 * pair_index, 4 + 2 * pair_index
        unit = _linear(((centers[p], Q(1), Q(0)), (centers[pi], Q(0), Q(1)),
                        (centers[i], Q(-1, 2), Q(-1, 2)),
                        (centers[j], Q(-1, 2), Q(-1, 2))))
        # |(1+i)/2| <= 1 bounds the two diagonal tomography coefficients.
        error = total_errors[p] + total_errors[pi] + total_errors[i] + total_errors[j]
        units[i, j], units[j, i] = unit, _adjoint(unit)
        unit_errors[i, j] = unit_errors[j, i] = error
    J = {}
    for i in range(3):
        J[str(i) + str(i)] = {"real": list(map(str, probabilities["diag" + str(i)])), "imag": ["0", "0"]}
    for i, j in PAIRS:
        a, b = probabilities["diag" + str(i)], probabilities["diag" + str(j)]
        mean = (a[0] + b[0]) / 2, (a[1] + b[1]) / 2
        real_p, imaginary_p = probabilities["plus" + str(i) + str(j)], probabilities["plus_i" + str(i) + str(j)]
        real = real_p[0] - mean[1], real_p[1] - mean[0]
        imag = mean[0] - imaginary_p[1], mean[1] - imaginary_p[0]
        J[str(i) + str(j)] = {"real": list(map(str, real)), "imag": list(map(str, imag))}
        J[str(j) + str(i)] = {"real": list(map(str, real)), "imag": list(map(str, (-imag[1], -imag[0])))}
    k, records = (1 - d) * eta, []
    for i in range(3):
        for j in range(3):
            matrix, error = units[i, j], unit_errors[i, j]
            if _adjoint(matrix) != units[j, i]:
                raise ValueError("matrix-unit adjoint symmetry failed")
            ion = {key: value for key, value in matrix.items() if key == (dipole.ION, dipole.ION)}
            survive = {key: value for key, value in matrix.items() if dipole.ION not in key}
            if _linear(((ion, Q(1), Q(0)), (survive, Q(1), Q(0)))) != matrix:
                raise ValueError("ion/survival instrument incomplete")
            click = _linear(((survive, d, Q(0)), (ion, d + k, Q(0))))
            no_click = _linear(((survive, 1 - d, Q(0)), (ion, 1 - d - k, Q(0))))
            if _linear(((click, Q(1), Q(0)), (no_click, Q(1), Q(0)))) != matrix:
                raise ValueError("CEM instrument incomplete")
            trace = [sum((value[part] for (a, b), value in matrix.items() if a == b), Q(0)) for part in (0, 1)]
            if not (trace[0] - error <= int(i == j) <= trace[0] + error and abs(trace[1]) <= error):
                raise ValueError("matrix-unit trace preservation enclosure failed")
            records.append({"input": [i, j], "Phi": _encoded_branch(matrix, error),
                            "trace_center": list(map(str, trace)),
                            "Phi_ion": _encoded_branch(ion, error), "Phi_survive": _encoded_branch(survive, error),
                            "click": _encoded_branch(click, error), "no_click": _encoded_branch(no_click, error)})
    return {"tomography": tomography, "matrix_units": records, "J": J,
            "detector": {"d": str(d), "eta": str(eta), "k": str(k)},
            "ion_survival_completeness_checked": True, "CEM_completeness_checked": True,
            "matrix_unit_adjoint_symmetry_checked": True,
            "matrix_unit_trace_preservation_enclosure_checked": True,
            "maximum_matrix_unit_trace_norm_error_upper": str(max(unit_errors.values()))}


def propagate(segments, *, d=0, eta=1, bits=240, order=80, norm_cap=4, max_steps=100000):
    cap, (d, eta) = _controller(segments, bits, order, norm_cap, max_steps), _detector(d, eta)
    quantum = 1 << bits
    states = [{key: tuple(int(value * quantum) for value in pair) for key, pair in matrix.items()}
              for matrix in initial_densities()]
    errors, coefficients, certificates, steps = [Q(0)] * 9, Q(0), [], 0
    for segment in segments:
        generator, count, dt, certificate = _setup(segment, bits, order, quantum, cap)
        if steps + count > max_steps:
            raise ValueError("qutrit step budget exceeded")
        _advance_segment(generator, count, dt, states, errors, quantum, order, certificate)
        steps += count
        coefficients += segment.duration * generator.generator_difference_bound
        certificate.update({"density_centers_after_segment": [full._encode_density(state, quantum) for state in states],
                            "numerical_error_bounds_after_segment": list(map(str, errors))})
        certificates.append(certificate)
    return {"schema": "stage10-atomic-qutrit-channel/v1", "physical_dimension": full.DIMENSION,
            "input_dimension": 3, "matrix_unit_inputs": 9, "tomography_inputs": 9,
            "complex_density_coordinates": full.COMPLEX_COORDINATES,
            "rounding_complex_coordinates": full.COMPLEX_COORDINATES,
            "basis": [{"family": state.family, "F": state.f, "m": state.m, "index": index}
                      for state, index in zip(BASIS, INDICES)],
            "initial_inventories": _inventories(), "initial_state_names": list(NAMES),
            "bits": bits, "order": order, "norm_cap": str(cap), "steps": steps,
            "pulse_certificates": certificates,
            "coefficient_trace_norm_error": str(coefficients),
            "source_bindings": _bindings(),
            "raw_program_sha256": full._program_digest([segment.record() for segment in segments]),
            "center_complete_positivity_claimed": False, "caller_density_supplied": False,
            "actual_hardware_identity_asserted": False, "actual_source_incidence_asserted": False,
            "controller_advance": False,
            **_derive(states, errors, coefficients, quantum, d, eta)}


def verify_certificate(report, segments=None, *, d=None, eta=None):
    if (report.get("schema") != "stage10-atomic-qutrit-channel/v1"
            or report.get("physical_dimension") != full.DIMENSION or report.get("input_dimension") != 3
            or any(report.get(key) != 9 for key in ("matrix_unit_inputs", "tomography_inputs"))
            or any(report.get(key) != full.COMPLEX_COORDINATES for key in
                   ("complex_density_coordinates", "rounding_complex_coordinates"))
            or report.get("source_bindings") != _bindings()):
        raise ValueError("qutrit identity/source mismatch")
    if (report.get("initial_inventories") != _inventories() or report.get("initial_state_names") != list(NAMES)
            or report.get("basis") != [{"family": state.family, "F": state.f, "m": state.m, "index": index}
                                     for state, index in zip(BASIS, INDICES)]
            or any(report.get(key) is not False for key in
                   ("center_complete_positivity_claimed", "caller_density_supplied", "actual_hardware_identity_asserted",
                    "actual_source_incidence_asserted", "controller_advance"))):
        raise ValueError("qutrit source inventory/scope mismatch")
    records = [certificate["raw_segment"] for certificate in report["pulse_certificates"]]
    if not records or report.get("raw_program_sha256") != full._program_digest(records):
        raise ValueError("qutrit raw program binding mismatch")
    if segments is not None and records != [segment.record() for segment in segments]:
        raise ValueError("qutrit certificate belongs to different raw program")
    raw = tuple(full.Segment.from_record(record) for record in records)
    bits, order = report["bits"], report["order"]
    cap = _controller(raw, bits, order, report["norm_cap"], max(1, report["steps"]))
    background, efficiency = _detector(report["detector"]["d"], report["detector"]["eta"])
    if (d is not None and background != full.exact(d)) or (eta is not None and efficiency != full.exact(eta)):
        raise ValueError("qutrit detector binding mismatch")
    quantum = 1 << bits
    states = [{key: tuple(int(value * quantum) for value in pair) for key, pair in matrix.items()}
              for matrix in initial_densities()]
    errors, coefficients, steps = [Q(0)] * 9, Q(0), 0
    for segment, certificate in zip(raw, report["pulse_certificates"]):
        generator, count, dt, expected = _setup(segment, bits, order, quantum, cap)
        if any(certificate.get(key) != value for key, value in expected.items()):
            raise ValueError("qutrit generator/error certificate mismatch")
        _advance_segment(generator, count, dt, states, errors, quantum, order, expected)
        coefficients += segment.duration * generator.generator_difference_bound
        steps += count
        if (certificate.get("density_centers_after_segment") != [full._encode_density(state, quantum) for state in states]
                or certificate.get("numerical_error_bounds_after_segment") != list(map(str, errors))):
            raise ValueError("qutrit center recurrence certificate mismatch")
    if report["steps"] != steps or report["coefficient_trace_norm_error"] != str(coefficients):
        raise ValueError("qutrit accumulated error/steps mismatch")
    expected = _derive(states, errors, coefficients, quantum, background, efficiency)
    if any(report.get(key) != value for key, value in expected.items()):
        raise ValueError("qutrit channel/J/instrument certificate mismatch")
    return True
