def zero(A): equal(clean(A), s.zeros(*A.shape))


def asset(path):
    record = json.loads(path.read_text())
    for group in ('source_sha256', 'input_sha256'):
        for name, expected in record.get(group, {}).items():
            assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest() == expected, name
    return record


class ActualOnshellPhaseSources:
    def __init__(self):
        self.vertices = asset(BASE/'matter-vertices/receipt.json')
        self.exchange = asset(BASE/'matter-vertices/exchange.json')
        self.active = asset(BASE/'active-gauge/receipt.json')
        self.phase = asset(BASE/'full-phase/receipt.json')
        self.modes = asset(BASE/'matter-modes/source.json')
        self.residue = asset(BASE/'kinetic-residue/receipt.json')
        self.spin_scale = s.sympify(self.residue['source_spin_scale'])
        self.action_factor = s.sympify(self.residue['right_normalization_factor'])
        self.kinetic_pair = decode(self.residue['kinetic_pair_matrix'])
        assert s.simplify(self.spin_scale*self.action_factor**2) == 1
        self.D = decode(self.vertices['full_stationary_Dirac_operator'])
        self.F = decode(self.modes['source_isometry'])
        self.Pfree = decode(self.modes['free_projection'])
        self.H0 = decode(self.modes['original_H_constant'])
        self.Hspace = [decode(row) for row in self.modes['original_H_spatial']]
        self.time_scale = s.sympify(self.modes['time_scale'])
        self.N, self.frequency = map(s.sympify, (self.phase['source_lapse'], self.phase['source_frequency']))
        self.S = clean(s.kronecker_product(GAMMA[0]*s.diag(-1, -1, 1, 1), s.eye(63)))
        self.Q = decode(self.phase['phase_generator'])
        self.operators = {row['field']: decode(row['operator']) for row in self.vertices['active_289_bosonic_source_operators']}
        self.ordering = self.exchange['source_field_indices']
        self.injection = s.SparseMatrix(289, len(self.ordering), {(field, column): 1 for column, field in enumerate(self.ordering)})
        self.null_map = decode(self.exchange['local_source_compatibility_map'])
        scalar = next(row for row in self.exchange['source_contact_terms'] if row['groups'] == ['scalar_Ward'])
        self.scalar_contact_map = decode(scalar['source_map'])
        self.dual_map = decode(self.exchange['independent_dual_source_map'])
        self.sigma = [s.Matrix([[0, 1], [1, 0]]), s.Matrix([[0, -s.I], [s.I, 0]]), s.diag(1, -1)]
        self.radius = 15*s.sqrt(2)/32

    def leg(self, degree, direction):
        block = next(row for row in self.modes['blocks'] if row['chirality'] == 1 and row['degree'] == degree and row['kind'] == 'singlet')
        direction = s.Matrix(direction)
        assert (direction.T*direction)[0] == 1
        projector = (s.eye(2)+sum((direction[j]*self.sigma[j] for j in range(3)), s.zeros(2)))/2
        column = next(j for j in range(2) if projector[:, j] != s.zeros(2, 1))
        spin = projector[:, column]
        spin = clean(spin/s.sqrt((spin.H*spin)[0]))
        frame = self.F[:, block['first_column']:block['first_column']+2]
        vector = clean(frame*spin)
        momentum = clean(self.radius*direction)
        h = clean(self.time_scale*(self.H0+sum((momentum[j]*self.Hspace[j]/s.sqrt(2) for j in range(3)), s.zeros(252))))
        # Rayleigh readback is followed by the full eigen-equation, so energy
        # is generated from the source action rather than imposed as a shell.
        energy = s.simplify((vector.H*h*vector)[0])
        stationary = s.simplify(energy-self.frequency*block['phase_charge'])
        derivative = s.Matrix([-s.I*stationary, *[s.I*k for k in momentum]])
        symbol = clean(self.D.subs(dict(zip(P, derivative))))
        zero(h*vector-energy*vector)
        zero(symbol*vector); zero(vector.H*self.S*symbol)
        assert s.simplify((vector.H*vector)[0]-1) == 0
        zero(self.Pfree*vector-vector)
        zero(self.Q*vector-block['phase_charge']*vector)
        assert s.simplify(energy-s.conjugate(energy)) == 0
        action_vector = clean(self.action_factor*vector)
        assert s.simplify((action_vector.H*self.kinetic_pair*action_vector)[0]) == 1
        zero(symbol*action_vector); zero(action_vector.H*self.S*symbol)
        equal(clean(action_vector*action_vector.H), clean(vector*vector.H/self.spin_scale))
        return {'degree': degree, 'spin': spin, 'vector': vector, 'action_vector': action_vector, 'momentum': momentum,
                'energy': energy, 'stationary_energy': stationary,
                'phase_charge': block['phase_charge'], 'derivative': derivative}

    def current(self, outgoing, incoming):
        pin, pout = dict(zip(P, incoming['derivative'])), dict(zip(P, outgoing['derivative']))
        values = []
        for field in self.ordering:
            a, b = self.operators[field].subs(pin), self.operators[field].subs(pout)
            values.append(s.simplify(s.sqrt(2)*(outgoing['action_vector'].H*(self.S*a+b.H*self.S)*incoming['action_vector'])[0]/2))
        return clean(s.Matrix(values))

    def sources(self):
        legs = [self.leg(4, [0, 0, 1]), self.leg(4, [s.Rational(4, 5), 0, s.Rational(-3, 5)]),
                self.leg(2, [0, 0, -1]), self.leg(2, [s.Rational(-4, 5), 0, s.Rational(3, 5)])]
        j1, j2 = self.current(legs[1], legs[0]), self.current(legs[3], legs[2])
        r1, r2 = legs[0]['derivative']-legs[1]['derivative'], legs[2]['derivative']-legs[3]['derivative']
        zero(r1+r2); assert r1[0] == r2[0] == 0
        target = s.Matrix([-3*s.sqrt(2)/8, 0, 3*s.sqrt(2)/4])
        equal(r1[1:, :]/s.I, target)
        zero(legs[0]['momentum']+legs[2]['momentum']-legs[1]['momentum']-legs[3]['momentum'])
        assert legs[0]['energy'] == legs[1]['energy'] and legs[2]['energy'] == legs[3]['energy']
        currents = []
        for current, transfer in ((j1, r1), (j2, r2)):
            assert current.todok()
            at = dict(zip(P, transfer))
            zero(self.null_map.subs(at)*current)
            zero(self.scalar_contact_map.subs(at)*current)
            zero(self.dual_map.subs(at)*current)
            # The extra radical is fixed by the actual outgoing spinor. The
            # reduced exact-field calculation retains and restores it linearly.
            scaled = clean(current*s.sqrt(5)).applyfunc(s.simplify)
            dm(scaled)
            equal(scaled/s.sqrt(5), current)
            currents.append({'transfer': transfer, 'current97': current,
                'current289': clean(self.injection*current), 'scaled_current289': clean(self.injection*scaled),
                'physical_current_factor': 1/s.sqrt(5)})
        zero(self.current(legs[3], legs[0])); zero(self.current(legs[1], legs[2]))
        # These legs have no peripheral scalar source. This is a direct
        # original70-vertex selection readout, not a deletion of scalar61.
        for outgoing, incoming in ((legs[1], legs[0]), (legs[3], legs[2])):
            for row in self.vertices['primitive_vertices']:
                if row['group'] != 'scalar': continue
                V = decode(row['operator'])
                a, b = V.subs(dict(zip(P, incoming['derivative']))), V.subs(dict(zip(P, outgoing['derivative'])))
                value = s.simplify((outgoing['action_vector'].H*(self.S*a+b.H*self.S)*incoming['action_vector'])[0])
                assert value == 0
        return legs, currents

    def reference_response(self, source):
        """Independent original four-block readback, not the forcing definition."""
        at = dict(zip(P, source['transfer']))
        current = clean(source['current97']*s.sqrt(5)).applyfunc(s.simplify)
        A = clean(decode(self.exchange['canonical_operator']).subs(at))
        J = clean(decode(self.exchange['canonical_source_map']).subs(at))
        force = mul(J, current)
        numerator, denominator = dm(A).solve_den(dm(force), method='rref')
        response = clean((numerator.to_Matrix()/DOMAIN.to_sympy(denominator)).applyfunc(s.simplify))
        equal(mul(A, response), force)
        local = mul(decode(self.exchange['contact_field_response']).subs(at), current)
        propagated = mul(decode(self.exchange['canonical_field_lift']).subs(at), response)
        field = clean(local+propagated)
        original = polynomial(self.active['Fourier_Jacobi_entries'], 289, 289)
        original = clean(original.xreplace({v: P[int(str(v)[1:])] for v in original.free_symbols}).subs(at))
        equal(mul(original, field), source['scaled_current289'])
        # All additional response ports are evaluated on this same actual
        # current before their zero contribution is recorded.
        zero(mul(self.dual_map.subs(at), current))
        zero(mul(self.scalar_contact_map.subs(at), current))
        return {'canonical_response': response, 'Contact_response': local,
                'propagated_response': propagated, 'full289_response': field,
                'original289_operator': original, 'canonical_force': force}


class CommonOnshellForcing:
    def __init__(self):
        self.spatial = SpatialActiveSplice()
        self.canonical_reader = self.original_canonical_reader()

    def original_canonical_reader(self):
        m, index = self.spatial, self.spatial.index
        n = len(m.split.active['fields'])
        selector = lambda rows: s.SparseMatrix(len(rows), n, {(i, row): 1 for i, row in enumerate(rows)})
        de = selector([index['coframe', (a, mu)] for a in range(4) for mu in range(4)])
        domega = selector([index['Lorentz', (mu, a)] for mu in range(4) for a in range(6)])
        dA = selector([index['gauge_A', (mu, a)] for mu in range(4) for a in range(12)])
        matter = lambda label: mul(m.current_real_frame, selector([index[label, (im, spin, color)]
            for im in range(2) for spin in range(4) for color in range(3)]))
        psi, chi = matter('primal_H'), matter('dual_H')
        Pi_e = clean(m.Gt.T*domega+m.dGt_omega*de)
        Bmag = selector([index['gauge_B', (pair, a)] for pair in range(3, 6) for a in range(12)])
        Pi_A = mul(s.kronecker_product(s.eye(3), m.c.gauge.gram), Bmag)
        phi = mul(m.split.J, selector(list(range(m.split.J.cols))))
        Pi_phi = clean(-(Z*phi+m.split.orbit*dA[:12, :])/m.split.N)
        self.scalar_momentum_reader = poly(Pi_phi)
        self.gauge_A0_selector = selector([index['gauge_A', (0, a)] for a in range(12)])
        matter_momentum = clean(m.p_from_chi*chi+m.p_from_e*de)
        q = s.Matrix.vstack(de[list(FREE), :], mul(m.c.graph.dual_R.T, phi), dA[12:, :], psi)
        p = s.Matrix.vstack(Pi_e[list(FREE), :], clean(m.split.R.T*Pi_phi), Pi_A, matter_momentum)
        return poly(clean(q.col_join(p)))

    def build(self, sign, source, reference):
        k = tuple(source['transfer'][1:, :]/s.I)
        reducer = ForcedHamiltonianReduction(k)
        common = SourceCommonRetardedPhase(sign)
        equal(s.Matrix(common.fiber['k']), s.Matrix(k))
        assert (reducer.A-common.active.A).is_zero_matrix
        j = poly(source['scaled_current289'])
        assert dm(reducer.at(reducer.Ward*j, 0)).is_zero_matrix
        spatial = self.spatial
        slice_reader = poly(spatial.native_slice_reader(k))
        ward = poly(spatial.ward.subs(dict(zip(P, [Z, *[s.I*v for v in k]]))))
        W = slice_reader*ward
        assert reducer.degree(W) == 0
        Wi = poly(W.convert_to(DOMAIN).inv())
        fixed = lambda value: value-ward*Wi*slice_reader*value
        dynamic_field = fixed(reducer.full_field_lift)
        particular_field = fixed(reducer.full_field_particular*j)
        Q = self.canonical_reader*dynamic_field
        # Right polynomial division is generated before the response is
        # solved. Thus its source contribution is not read backwards from a
        # desired Green field or a projected arbitrary current.
        Qmatrix = Q.to_Matrix()
        coefficients = [dm(Qmatrix.applyfunc(lambda x: s.expand(x).coeff(Z, n)))
                        for n in range(reducer.degree(Q)+1)]
        remainder = coefficients[-1]
        quotient = DM.zeros(Q.shape, POLY)
        for n in range(len(coefficients)-2, -1, -1):
            quotient = quotient.scalarmul(POLY.gens[0])+poly(remainder)
            remainder = coefficients[n]+remainder*reducer.A
        active_X = common.X.extract(range(common.X.shape[0]), range(reducer.A.shape[0]))
        assert (remainder-active_X).is_zero_matrix
        operator = poly(DM.eye(reducer.A.shape, DOMAIN)).scalarmul(POLY.gens[0])-poly(reducer.A)
        assert (Q-poly(active_X)-quotient*operator).is_zero_matrix
        forcing = reducer.forcing*j
        affine_phase = self.canonical_reader*particular_field+quotient*forcing
        f0 = dm(reducer.at(forcing, 0))
        physical_forcing = active_X*f0
        assert (common.T*physical_forcing-physical_forcing).is_zero_matrix
        response = common.resolvent(physical_forcing, 0)
        xi = common.R*response
        tail = xi.extract(range(reducer.A.shape[0], xi.shape[0]), [0])
        assert tail.is_zero_matrix
        xi = xi.extract(range(reducer.A.shape[0]), [0])
        assert (-reducer.A*xi-f0).is_zero_matrix
        whole_field = dm(reducer.at(dynamic_field, 0))*xi+dm(reducer.at(particular_field, 0))
        whole_phase = response+dm(reducer.at(affine_phase, 0))
        assert (dm(reducer.at(self.canonical_reader, 0))*whole_field-whole_phase).is_zero_matrix
        field = clean(whole_field.to_Matrix())
        equal(mul(reference['original289_operator'], field), source['scaled_current289'])
        # The independent four-block inverse may choose another Ward
        # representative. Fix it by the same original parameter on all fields.
        fixed_reference = fixed(poly(reference['full289_response']))
        equal(field, clean(reducer.at(fixed_reference, 0)))
        descriptor = dm(reducer.at(reducer.dynamic_lift, 0))*xi+dm(reducer.at(reducer.total_particular*j, 0))
        descriptor_source = dm(reducer.at(reducer.source*j, 0))
        assert (-reducer.energy*descriptor-descriptor_source).is_zero_matrix
        original_gauss = mul(spatial.model.at(spatial.model.Gauss, k), whole_phase.to_Matrix())
        affine_gauss = mul(spatial.model.at(spatial.model.Gauss, k), reducer.at(affine_phase, 0))
        equal(original_gauss, affine_gauss)
        zero(mul(spatial.model.at(spatial.model.slice, k), whole_phase.to_Matrix()))
        Pi_phi = mul(reducer.at(self.scalar_momentum_reader, 0), field)
        broken_prediction = spatial.model.broken_scalar_momentum(k, whole_phase.to_Matrix())
        affine_normal_momentum = clean(Pi_phi-broken_prediction)
        full_gauss = clean(spatial.model.full_Gauss(k, whole_phase.to_Matrix())+mul(spatial.split.orbit.T, affine_normal_momentum))
        A0_source = mul(self.gauge_A0_selector, source['scaled_current289'])
        equal(full_gauss, A0_source)
        equal(affine_normal_momentum, mul(spatial.c.graph.O, spatial.c.graph.constraints.gram.inv(), spatial.c.graph.select.T, A0_source))
        assert full_gauss.todok()
        print('PASS original full12 Gauss equals the actual A0 source, including its normal scalar momentum', sign, flush=True)
        phase_constraint = s.eye(1214)-common.T.to_Matrix()
        equal(mul(phase_constraint, whole_phase.to_Matrix()), mul(phase_constraint, reducer.at(affine_phase, 0)))
        return {'momentum': list(map(str, k)), 'source_factor': str(source['physical_current_factor']),
                'factored_physical_forcing126': encode(f0.to_Matrix()),
                'factored_physical_response126': encode(xi.to_Matrix()),
                'factored_common1214_forcing': encode(physical_forcing.to_Matrix()),
                'factored_common1214_retarded_response': encode(response.to_Matrix()),
                'factored_affine_phase_polynomial': encode(affine_phase.to_Matrix()),
                'factored_full_source_phase': encode(whole_phase.to_Matrix()),
                'factored_source_induced_Gauss': encode(original_gauss),
                'factored_source_induced_full12_Gauss': encode(full_gauss),
                'factored_source_induced_normal_scalar_momentum': encode(affine_normal_momentum),
                'factored_full289_source_response': encode(field),
                'full289_reference_after_same_Ward_slice': True,
                'full289_original_forced_Euler': True,
                'descriptor_source_and_affine_constraints': True,
                'canonical_right_division_remainder_is_original_active_embedding': True,
                'all_source_normalization_restored_by_factor': str(source['physical_current_factor']),
                'zero_frequency_use': 'Meromorphic rational/tree readback at z=0; no convergent zero-frequency Laplace integral is inferred.'}


