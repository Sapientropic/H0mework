#!/usr/bin/env python3
"""Affine source reduction of the original presymplectic descriptor.

The forcing and all source derivatives are generated by the descending
consistency chain, before a resolvent is used. Compatibility residues factor
through the original nine Ward rows. No source is projected into that kernel.
"""
from __future__ import annotations

import hashlib
import json
import time
import sympy as s
from sympy.polys.matrices import DomainMatrix as DM

from dynamic import HERE, ROOT, ROOT_ID
from retained_hamiltonian_reduction import DOMAIN, K, P, decode, encode, null, identity
from source_spatial_active_phase_splice import dm

Z = s.Symbol('source_laplace')
POLY = DOMAIN.poly_ring(Z)
RATIONAL = DOMAIN.frac_field(Z)


def zero(A):
    assert A.is_zero_matrix


def poly(A):
    if isinstance(A, DM): return A.convert_to(POLY)
    # Build the polynomial ring coefficientwise using the same fast exact
    # algebraic homomorphism as the signed spatial phase producer.
    entries = {}
    for (i, j), value in s.SparseMatrix(A).todok().items():
        p = s.Poly(s.expand(value), Z)
        if p.is_zero: continue
        coefficients = dm(s.Matrix([[p.nth(n) for n in range(p.degree()+1)]]))
        element = POLY.zero
        for n, coefficient in coefficients.rep.get(0, {}).items():
            element += POLY.convert(coefficient, DOMAIN)*POLY.gens[0]**n
        if element: entries.setdefault(i, {})[j] = element
    return DM(entries, A.shape, POLY).to_sparse()


def partial_solution(A, B):
    """Pivot-generated solution with its complete, unaltered residual."""
    rows = A.transpose().rref()[1]
    columns = A.rref()[1]
    inverse = A.extract(rows, columns).inv()
    values = poly(inverse)*poly(B).extract(rows, range(B.shape[1]))
    result = DM({i: values.rep[j] for j, i in enumerate(columns) if j in values.rep},
                (A.shape[1], B.shape[1]), POLY)
    return result, poly(A)*result-poly(B)


class ForcedHamiltonianReduction:
    def __init__(self, momentum):
        self.momentum = tuple(map(s.sympify, momentum))
        self.record = json.loads((HERE/'retained_matter_action.json').read_text())
        self.catalog = json.loads((HERE/'retained_hamiltonian_reduction.json').read_text())
        for receipt in (self.record, self.catalog):
            assert receipt['root'] == ROOT_ID
            for group in ('source_sha256', 'input_sha256'):
                for name, digest in receipt[group].items():
                    assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest() == digest, name
        matched = next((row, sign) for row in self.catalog['source_momenta'] for sign in (1, -1)
                       if tuple(sign*s.sympify(k) for k in row['momentum']) == self.momentum)
        old, sign = matched
        def get(key):
            matrix = decode(old[key])
            return dm(matrix if sign == 1 else matrix.conjugate())
        self.section = get('velocity_quotient_section')
        self.retraction = get('velocity_quotient_retraction')
        at = dict(zip(K, self.momentum))
        omega242 = dm(decode(self.record['presymplectic_form']).subs(at))
        energy242 = dm(decode(self.record['Legendre_energy_hessian']).subs(at))
        section_adjoint = dm(self.section.to_Matrix().H)
        self.omega = section_adjoint*omega242*self.section
        self.energy = section_adjoint*energy242*self.section
        self.A = get('Hamiltonian_generator')
        self.quotient = get('quotient_map')
        self.quotient_section = get('quotient_section')
        self.original_consistent = get('consistent_initial_data_embedding')
        self.generator = get('consistent_generator')
        self.free = get('free_derivative_directions')
        evaluate = dict(zip(P, [Z, *[s.I*k for k in self.momentum]]))
        self.lift = poly(decode(self.record['retained_field_lift']).subs(evaluate))
        self.contact = poly(decode(self.record['auxiliary_only_contact']).subs(evaluate))
        retained_source = poly(decode(self.record['retained_source_readback']).subs(evaluate))
        self.source = poly(section_adjoint)*DM.vstack(retained_source, DM.zeros((121, 289), POLY))
        full_ward = decode(self.record['retained_field_lift'])*decode(self.record['normal_coordinate_change'])[:, 112:121]
        negative = dict(zip(P, [-Z, *[-s.I*k for k in self.momentum]]))
        self.Ward = poly(full_ward.subs(negative).T)
        ward_field = self.Ward.convert_to(RATIONAL)
        ward_columns = ward_field.rref()[1]
        assert len(ward_columns) == 9
        self.ward_columns = ward_columns
        self.ward_inverse = ward_field.extract(range(9), ward_columns).inv()
        self.obstructions = []
        C, particular = identity(172), DM.zeros((172, 289), POLY)
        self.chain = []
        z = POLY.gens[0]
        self.descriptor = poly(self.omega).scalarmul(z)-poly(self.energy)
        for _ in range(173):
            B, F = self.omega*C, self.energy*C
            left_null = null(B.transpose()).transpose()
            constraint = left_null*F
            rank = len(constraint.rref()[1])
            forcing = self.source-self.descriptor*particular
            rhs = -poly(left_null)*forcing
            correction, obstruction = partial_solution(constraint, rhs)
            self.obstructions.append(self.factor_Ward(obstruction))
            self.chain.append({'carrier_dimension': C.shape[1], 'new_constraints': rank,
                               'affine_degree': self.degree(particular),
                               'Ward_obstruction_nonzero_entries': len(obstruction.to_Matrix().todok())})
            if rank == 0: break
            particular += poly(C)*correction
            C = C*null(constraint)
        else: raise AssertionError('finite descriptor consistency chain failed to terminate')
        zero(C-self.original_consistent)
        self.consistent = C
        self.affine_particular = particular
        reduced_source = self.source-self.descriptor*particular
        consistent_forcing, obstruction = partial_solution(self.omega*C, reduced_source)
        self.obstructions.append(self.factor_Ward(obstruction))
        self.consistent_forcing = consistent_forcing
        self.forcing = poly(self.quotient)*consistent_forcing
        # The stored quotient section is not invariant under the descriptor.
        # Its discrepancy is removed by the original free derivative columns,
        # whose Omega image is zero, not by the target Green response.
        U = C*self.free
        zero(self.omega*U)
        EU = self.energy*U
        discrepancy = self.omega*C*self.quotient_section*self.A-self.energy*C*self.quotient_section
        homogeneous_correction, residual = partial_solution(EU, discrepancy)
        zero(residual)
        self.dynamic_lift = poly(C*self.quotient_section)+poly(U)*homogeneous_correction
        zero(poly(self.omega)*self.dynamic_lift*poly(self.A)-poly(self.energy)*self.dynamic_lift)
        homogeneous_consistent = poly(self.quotient_section)+poly(self.free)*homogeneous_correction
        zero(poly(self.quotient)*homogeneous_consistent-poly(identity(self.A.shape[0])))
        source_discrepancy = poly(self.omega)*self.dynamic_lift*self.forcing-poly(self.omega*C)*consistent_forcing
        affine_correction, residual = partial_solution(EU, source_discrepancy)
        self.obstructions.append(self.factor_Ward(residual))
        self.total_particular = particular+poly(U)*affine_correction
        self.descriptor_residual = (poly(self.omega)*self.dynamic_lift*self.forcing+
                                   self.descriptor*self.total_particular-self.source)
        self.descriptor_Ward_factor = self.factor_Ward(self.descriptor_residual)
        self.z = Z
        self.homogeneous_correction = homogeneous_correction
        self.affine_correction = affine_correction
        # Full first-order jet reconstruction is kept in original ordering.
        self.phase_lift = poly(self.section)*self.dynamic_lift
        self.phase_particular = poly(self.section)*self.total_particular
        self.retained_lift = self.phase_lift.extract(range(121), range(self.A.shape[0]))
        self.retained_particular = self.phase_particular.extract(range(121), range(289))
        self.full_field_lift = self.lift*self.retained_lift
        self.full_field_particular = self.contact+self.lift*self.retained_particular
        # Recombine the first-order Euler rows into the original second-order
        # retained action. This pays the full field lift before any Green use.
        jet_reader = DM.hstack(poly(identity(121)), -poly(identity(121)).scalarmul(z))
        retraction_adjoint = poly(dm(self.retraction.to_Matrix().H))
        euler_reader = jet_reader*retraction_adjoint
        self.euler_physical_factor = euler_reader*poly(self.omega)*self.dynamic_lift
        retained_operator = poly(decode(self.record['retained_operator']).subs(evaluate))
        dynamic_operator = poly(identity(self.A.shape[0])).scalarmul(z)-poly(self.A)
        zero(retained_operator*self.retained_lift-self.euler_physical_factor*dynamic_operator)
        euler_residual = (retained_operator*self.retained_particular+
                          self.euler_physical_factor*self.forcing-retained_source)
        self.euler_Ward_factor = self.factor_Ward(euler_residual)
        zero(euler_residual-euler_reader*self.descriptor_residual)

    @staticmethod
    def degree(matrix):
        return int(max((s.degree(value, Z) for value in matrix.to_Matrix().todok().values()), default=-1))

    def factor_Ward(self, residual):
        """Audit a generated obstruction; this never modifies an input source."""
        R = residual.convert_to(RATIONAL)
        coefficient = R.extract(range(R.shape[0]), self.ward_columns)*self.ward_inverse
        zero(R-coefficient*self.Ward.convert_to(RATIONAL))
        return coefficient

    def at(self, matrix, z=0):
        return matrix.to_Matrix().subs(Z, s.sympify(z))

    def report(self):
        return {'momentum': list(map(str, self.momentum)), 'consistency_chain': self.chain,
            'original_Ward_map': encode(self.Ward),
            'original_descriptor_source': encode(self.source),
            'affine_particular': encode(self.affine_particular),
            'consistent_forcing': encode(self.consistent_forcing),
            'physical_forcing': encode(self.forcing),
            'descriptor_dynamic_lift': encode(self.dynamic_lift),
            'descriptor_total_particular': encode(self.total_particular),
            'descriptor_Ward_factor': encode(self.descriptor_Ward_factor),
            'retained_Euler_physical_factor': encode(self.euler_physical_factor),
            'retained_Euler_Ward_factor': encode(self.euler_Ward_factor),
            'stage_Ward_factors': [encode(value) for value in self.obstructions],
            'retained_field_lift': encode(self.retained_lift),
            'retained_field_particular': encode(self.retained_particular),
            'full289_field_lift': encode(self.full_field_lift),
            'full289_field_particular': encode(self.full_field_particular),
            'physical_dimension': self.A.shape[0],
            'forcing_polynomial_degree': self.degree(self.forcing),
            'total_particular_polynomial_degree': self.degree(self.total_particular),
            'homogeneous_section_correction_nonzero_entries': len(self.homogeneous_correction.to_Matrix().todok()),
            'affine_section_correction_nonzero_entries': len(self.affine_correction.to_Matrix().todok())}


def main():
    started = time.monotonic()
    k = (-3*s.sqrt(2)/8, s.S.Zero, 3*s.sqrt(2)/4)
    reports = []
    for sign in (1, -1):
        reduction = ForcedHamiltonianReduction(tuple(sign*v for v in k))
        reports.append(reduction.report())
        print('PASS original affine descriptor, Ward-factorized consistency and dynamic physical forcing', sign,
              reduction.chain, 'source degree', reduction.degree(reduction.forcing), flush=True)
    paths = [HERE/'source_forced_hamiltonian_reduction.py', HERE/'retained_matter_action.json',
             HERE/'retained_hamiltonian_reduction.json', HERE/'source_spatial_active_phase_splice.py']
    output = {'root': ROOT_ID, 'scope': 'ORIGINAL_AFFINE_DESCRIPTOR_AND_PHYSICAL_FORCING_AT_SIGNED_NONZERO_SOURCE_MOMENTA',
        'source_sha256': reduction.record['source_sha256'],
        'input_sha256': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths},
        'source_momenta': reports,
        'descriptor_identity': '(z Omega-E)(Edyn xi+Ptotal j)=B j modulo W(z)j whenever (z-A)xi=F(z)j',
        'construction': 'Original descending left-null constraints generate P(z); Omega*C pivot solve generates F(z). Original free-derivative columns repair the quotient section. No Green inverse is used.',
        'source_compatibility': 'Unaltered original289 current with W(z)j=0; every intermediate obstruction factors through these nine original Ward rows.',
        'contact': 'Caux is added once in full289_field_particular; affine scalar-Ward effects arise from the original descriptor constraints.',
        'lifetime_status': 'SOURCE_NATIVE_DYNAMIC_MEASURE_REQUIRED',
        'elapsed_seconds': round(time.monotonic()-started, 3)}
    (HERE/'source_forced_hamiltonian_reduction.json').write_text(json.dumps(output, separators=(',', ':'))+'\n')
    print('PASS source affine Hamiltonian reducer', output['elapsed_seconds'], 'seconds', flush=True)


if __name__ == '__main__': main()
