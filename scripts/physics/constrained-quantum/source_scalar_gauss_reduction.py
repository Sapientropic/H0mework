class SourceScalarGaussReduction:
    def __init__(self):
        self.constraints = SourceConstraintPreservation()
        self.common = SourceCommonHamiltonian()
        c = self.constraints
        self.R = c.projector[:, list(c.projector.rref()[1])]
        self.dual_R = clean(self.R*(self.R.T*self.R).inv())
        self.O = c.active
        self.select = c.select
        self.stabilizer = c.stabilizer
        equal(self.R.T*self.dual_R, s.eye(61))
        equal(self.O.T*self.R, s.zeros(9, 61))

    def gauss_without_scalar(self, A, Pi_A, spatial_Pi_A, psi, p):
        pure = self.common.gauge.gauss(A, Pi_A, spatial_Pi_A)
        matter = s.Matrix([real((s.I*p*R*psi)[0]) for R in self.common.rho])
        return {'pure': pure, 'matter': clean(matter), 'total': clean(pure+matter)}

    def embed(self, x, pi, A, Pi_A, spatial_Pi_A, psi, p):
        phi = clean(self.constraints.vacuum+self.R*x)
        peripheral = clean(self.dual_R*pi)
        D = clean(self.select.T*self.constraints.consistency_matrix(phi)*self.select)
        if D.det() == 0:
            raise ValueError('The source broken Gauss chart requires det D9(phi) != 0.')
        base = self.gauss_without_scalar(A, Pi_A, spatial_Pi_A, psi, p)
        scalar = s.Matrix([dot(peripheral, R*phi) for R in self.constraints.rho])
        base_total = clean(base['total']+scalar)
        normal = clean(-D.T.inv()*self.select.T*base_total)
        Pi_phi = clean(peripheral+self.O*normal)
        total = clean(base['total']+s.Matrix([dot(Pi_phi, R*phi) for R in self.constraints.rho]))
        return {'phi': phi, 'Pi_phi': Pi_phi, 'normal_momentum': normal,
                'broken_matrix': D, 'Gauss': total,
                'residual_stabilizer_Gauss': clean(self.stabilizer.T*total),
                'base_current': base, 'base_total': base_total}

    def retract(self, phi, Pi_phi):
        equal(self.constraints.potential_constraint(phi), s.zeros(12, 1))
        return {'x': clean(self.dual_R.T*(phi-self.constraints.vacuum)),
                'pi': clean(self.R.T*Pi_phi)}

    def time_connection(self, e, data, spatial_phi, A, parameters=None):
        return self.constraints.solve_time_connection(
            e, data['phi'], data['Pi_phi'], spatial_phi, A, parameters)['time_connection']

    def pullback_hamiltonian(self, e, Pi_e, spatial_e, x, pi, spatial_x,
                             A, Pi_A, spatial_A, spatial_Pi_A, psi, p, spatial_psi, multipliers):
        data = self.embed(x, pi, A, Pi_A, spatial_Pi_A, psi, p)
        spatial_phi = [clean(self.R*direction) for direction in spatial_x]
        connection = A.copy()
        connection[0, :] = self.time_connection(e, data, spatial_phi, A).T
        hamiltonian = self.common.hamiltonian(e, Pi_e, spatial_e, data['phi'], data['Pi_phi'],
            spatial_phi, connection, Pi_A, spatial_A, psi, p, spatial_psi, multipliers)
        # The functional A0 coefficient is -G only after retaining its actual
        # spatial boundary. Removing that divergence also removes the need to
        # supply spatial derivatives of the newly generated A0 graph.
        boundary_divergence = sum(contraction(spatial_Pi_A[i][i, :], connection[0, :])+
                                  contraction(Pi_A[i, :], spatial_A[i, :12]) for i in range(3))
        return {**data, 'connection': connection,
                'bulk_Hamiltonian': s.factor(hamiltonian['value']-boundary_divergence),
                'gauge_spatial_boundary_flux': clean(Pi_A*connection[0, :].T)}


def verify_fixed_slice(model):
    c = model.constraints
    phase = json.loads((HERE/'scalar_canonical_phase.json').read_text())
    equal(model.R, decode(phase['scalar_coordinate_embedding']))
    equal(s.diag(model.R, model.dual_R), decode(phase['canonical_phase_embedding']))
    equal(model.R*model.dual_R.T, c.projector)
    equal(model.R.row_join(model.O)*(model.R.row_join(model.O)).inv(), s.eye(70))
    x = s.Matrix(s.symbols('x0:61', real=True))
    pi = s.Matrix(s.symbols('pi0:61', real=True))
    zeta = s.Matrix(s.symbols('zeta0:9', real=True))
    dx = s.Matrix(s.symbols('dx0:61', real=True))
    dzeta = s.Matrix(s.symbols('dzeta0:9', real=True))
    phi = c.vacuum+model.R*x
    Pi = model.dual_R*pi+model.O*zeta
    equal(c.potential_constraint(phi), s.zeros(12, 1))
    assert s.expand(dot(Pi, model.R*dx)-dot(pi, dx)) == 0
    # zeta may depend on all remaining fields and momenta. Its arbitrary
    # differential disappears, so exterior differentiation adds no mixed form.
    assert s.expand(dot(model.O*dzeta, model.R*dx)) == 0
    D = c.consistency_matrix(phi)
    equal(D, D.T)
    equal(D*model.stabilizer, s.zeros(12, 3))
    gram = clean(model.O.T*model.O)
    equal(model.select.T*c.consistency_matrix(c.vacuum)*model.select, gram)
    assert gram.det() != 0
    return {'coordinate_dimension': 61, 'conjugate_phase_dimension': 122,
            'same_original_CCR_embedding': True, 'source_D9_determinant': str(gram.det()),
            'all61_scalar_coordinates_symbolic': True,
            'one_form': 'Pi_phi^T dphi = pi^T dx on phi=v+R*x, Pi_phi=R*(R^T*R)^-1*pi+O_b*zeta',
            'arbitrary_normal_momentum_differential_drops_out': True,
            'complete_joint_canonical_one_form_preserved': True,
            'domain': 'det D9(phi) != 0, with the original coframe/gauge Legendre guards unchanged'}


def verify_full_current_consumer(model):
    c, common = model.constraints, model.common
    background = common.scalar.exchange.active['actual_background']
    e = s.Matrix(background['coframe']).applyfunc(s.sympify)
    A = s.Matrix(background['gauge_connection']).applyfunc(s.sympify)
    x = s.Matrix([s.Rational((7*i+3) % 13-6, 10000) for i in range(61)])
    pi = s.Matrix([s.Rational((5*i+1) % 11-5, 37) for i in range(61)])
    Pi_A = s.Matrix(3, 12, lambda i, a: s.Rational((3*i+5*a+1) % 11-5, 29))
    spatial_Pi_A = [s.Matrix(3, 12, lambda j, a: s.Rational((i+2*j+3*a) % 7-3, 41)) for i in range(3)]
    psi = s.Matrix([s.Rational((5*i+1) % 13-6, 31)+s.I*s.Rational((3*i+2) % 11-5, 43) for i in range(252)])
    p = s.Matrix([[s.Rational((7*i+2) % 17-8, 47)+s.I*s.Rational((2*i+3) % 13-6, 53) for i in range(252)]])
    data = model.embed(x, pi, A, Pi_A, spatial_Pi_A, psi, p)
    assert data['normal_momentum'].todok()
    equal(model.select.T*data['Gauss'], s.zeros(9, 1))
    assert data['residual_stabilizer_Gauss'].todok()
    original = common.gauss(e, data['phi'], data['Pi_phi'], A, Pi_A, spatial_Pi_A, psi, p)
    equal(original['total'], data['Gauss'])
    equal(original['pure'], data['base_current']['pure'])
    equal(original['matter'], data['base_current']['matter'])
    assert (model.select.T*original['pure']).todok()
    assert (model.select.T*original['matter']).todok()
    back = model.retract(data['phi'], data['Pi_phi'])
    equal(back['x'], x); equal(back['pi'], pi)
    spatial_phi = [model.R*s.Matrix([s.Rational((j+i) % 5-2, 101) for j in range(61)]) for i in range(3)]
    A[0, :] = model.time_connection(e, data, spatial_phi, A).T
    kinematic = c.scalar_kinematics(e, data['phi'], data['Pi_phi'], spatial_phi, A)
    equal(c.orbit.T*kinematic['velocity'], s.zeros(12, 1))
    # Ambient scalar Hamiltonian's complete normal-momentum derivative vanishes
    # after the source-generated A0 update. This kills every graph chain term.
    equal(model.O.T*kinematic['velocity'], s.zeros(9, 1))
    h00 = kinematic['metric'][0, 0]
    normal_energy = s.factor(dot(model.O*data['normal_momentum'], model.O*data['normal_momentum'])/(2*h00))
    assert normal_energy != 0
    equal(model.dual_R.T*model.O, s.zeros(61, 9))
    wrong = common.gauss(e, data['phi'], model.dual_R*pi, A, Pi_A, spatial_Pi_A, psi, p)
    assert (model.select.T*wrong['total']).todok()
    # Actual common density, with every scalar/gauge/matter term retained.
    # Two broken A0 representatives have the same bulk energy on the graph;
    # a stabilizer change instead reads the retained Gauss constraint.
    spatial_A = s.zeros(3, 48)
    spatial_A[:, :12] = s.Matrix(3, 12, lambda i, a: s.Rational((i+3*a) % 7-3, 59))
    def bulk(connection):
        raw = common.hamiltonian(e, s.zeros(16, 1), s.zeros(48, 1),
            data['phi'], data['Pi_phi'], spatial_phi, connection, Pi_A, spatial_A,
            psi, p, [s.zeros(252, 1)]*3, s.zeros(10, 1))['value']
        boundary = sum(contraction(spatial_Pi_A[i][i, :], connection[0, :])+
                       contraction(Pi_A[i, :], spatial_A[i, :12]) for i in range(3))
        return s.factor(raw-boundary)
    energy = bulk(A)
    zero_A = A.copy(); zero_A[0, :] = s.zeros(1, 12)
    assert s.simplify(energy-bulk(zero_A)) == 0
    residual_A = A.copy(); residual_A[0, :] += model.stabilizer[:, 0].T
    defect = s.factor(bulk(residual_A)-energy)
    assert s.simplify(defect+data['residual_stabilizer_Gauss'][0]) == 0
    assert defect != 0
    public = model.pullback_hamiltonian(e, s.zeros(16, 1), s.zeros(48, 1), x, pi,
        [model.dual_R.T*value for value in spatial_phi], A, Pi_A, spatial_A, spatial_Pi_A,
        psi, p, [s.zeros(252, 1)]*3, s.zeros(10, 1))
    assert s.simplify(public['bulk_Hamiltonian']-energy) == 0
    rejected = False
    try:
        model.embed(-model.dual_R.T*c.vacuum, pi, A, Pi_A, spatial_Pi_A, psi, p)
    except ValueError:
        rejected = True
    assert rejected
    return {'full_primal_entries': 252, 'full_independent_canonical_dual_entries': 252,
            'native_Gauss_rows': 12, 'broken_rows_zero': 9,
            'residual_stabilizer_rows': 3, 'residual_rows_nonzero_retained': True,
            'original_full_Gauss_readback': True, 'Gauss_and_scalar_coordinate_roundtrip': True,
            'nonzero_native_and_matter_current_controls': True,
            'normal_scalar_momentum': encode(data['normal_momentum']),
            'residual_stabilizer_Gauss': encode(data['residual_stabilizer_Gauss']),
            'actual_D9_determinant': str(data['broken_matrix'].det()),
            'source_generated_A0_preserves_scalar_slice': True,
            'all_normal_momentum_Hamiltonian_chain_coefficients_zero': True,
            'same_common_bulk_Hamiltonian_broken_A0_independent': True,
            'original_gauge_spatial_flux_retained': True,
            'public_bulk_Hamiltonian_executed': True,
            'rank_drop_phi_zero_not_inverted': True,
            'residual_A0_energy_variation_reads_remaining_Gauss': str(defect),
            'normal_kinetic_energy': str(normal_energy),
            'discard_normal_momentum_negative_control_nonzero': True,
            'fixture_scope': 'scalar/broken-Gauss phase graph with full currents and spatial momentum jets; the three residual Gauss and coframe constraints remain explicit'}


