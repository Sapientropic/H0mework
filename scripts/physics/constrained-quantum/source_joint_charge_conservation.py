def source_real_car_lift(h):
    """Original rho=i h, i realify(rho), then the fixed source branch unitary."""
    H=s.SparseMatrix(s.kronecker_product(s.eye(4),h));rho=s.I*H
    I=s.eye(252);U=s.SparseMatrix(s.BlockMatrix([[I,s.I*I],[I,-s.I*I]]).as_explicit()/s.sqrt(2))
    Q=s.SparseMatrix(s.diag(s.I*rho,-s.conjugate(s.I*rho)))
    assert U*(s.I*realify(rho))*U.H==Q and Q.H==Q
    return Q


class SourceChargeProjectors:
    """Every polynomial is generated by the actual signed full504 source charge."""
    def __init__(self,charges):
        self.diagonals=tuple(tuple(Q.diagonal()) for Q in charges[:12])
        self.radii=tuple(sum(c==1 for c in row) for row in self.diagonals)
        for row,r in zip(self.diagonals,self.radii):
            assert set(row).issubset({s.S.NegativeOne,s.S.Zero,s.S.One})
            assert sum(c==-1 for c in row)==r and r>0
        assert sum(self.radii)==252

    def charge(self,sector,word):
        assert tuple(sorted(set(word)))==word and all(0<=j<504 for j in word)
        q=sum((self.diagonals[sector][j] for j in word),s.S.Zero)
        assert q.is_Integer and -self.radii[sector]<=q<=self.radii[sector]
        return q

    def polynomial_factors(self,sector,eigenvalue):
        r=self.radii[sector]
        assert isinstance(eigenvalue,int) and -r<=eigenvalue<=r
        return tuple((m,s.Rational(1,eigenvalue-m)) for m in range(-r,r+1) if m!=eigenvalue)

    def polynomial_value(self,sector,eigenvalue,value):
        out=s.S.One
        for m,c in self.polynomial_factors(sector,eigenvalue):
            out*=c*(value-m)
            if out==0:break
        return out

    def apply(self,sector,eigenvalue,state):
        return simplified({word:c*self.polynomial_value(sector,eigenvalue,self.charge(sector,word))
            for word,c in state.items()})

    def joint(self,charges,state):
        assert len(charges)==12
        for sector,value in enumerate(charges):state=self.apply(sector,int(value),state)
        return state

    def signature(self,word):return tuple(self.charge(a,word) for a in range(12))


def full_source_coefficient_closure(model,hermitian,charges):
    """Finite primitive inventory pays arbitrary original z,p, not one fixture."""
    common=model.leaf.weyl.native.joint.common
    elementary_spin=[]
    for i in range(4):
        for j in range(4):
            E=s.SparseMatrix(4,4,{(i,j):1})
            elementary_spin.append(s.SparseMatrix(s.kronecker_product(E,s.eye(63))))
    checked=0
    for h,Q in zip(hermitian,charges):
        H=s.SparseMatrix(s.kronecker_product(s.eye(4),h))
        for A in [*elementary_spin,*common.rho,*common.yukawa_basis]:
            commute(H,A);checked+=1
        for A in model.leaf.charges:
            commute(Q,A);checked+=1
        # Every actual coframe current is a spin4 block in each real branch.
        for A in elementary_spin:
            for slot in (0,1):
                R=s.SparseMatrix(504,504,{})
                R[252*slot:252*(slot+1),252*slot:252*(slot+1)]=A
                commute(Q,R);checked+=1
    return checked


def verify_diagonal_projectors(projectors):
    nodes=0;actual_words=[]
    for a,r in enumerate(projectors.radii):
        plus=[j for j,c in enumerate(projectors.diagonals[a]) if c==1]
        minus=[j for j,c in enumerate(projectors.diagonals[a]) if c==-1]
        for value in range(-r,r+1):
            word=tuple(plus[:value]) if value>=0 else tuple(minus[:-value])
            assert projectors.charge(a,word)==value
            for selected in range(-r,r+1):
                assert projectors.polynomial_value(a,selected,s.Integer(value))==int(selected==value)
            nodes+=1
        actual_words.append({'sector':a,'radius':r,'negative_extreme':minus,'positive_extreme':plus,
            'factor_count':2*r})
    return nodes,actual_words


