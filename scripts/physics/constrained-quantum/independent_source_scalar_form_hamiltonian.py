def zero(value): assert s.cancel(s.expand(value)) == 0
def state_equal(left, right): assert terms([(1, left), (-1, right)]) == {}


def raw_coefficients(raw, e, x, A):
    y = x.col_join(A.reshape(36, 1))
    phi = raw.v+raw.R*x
    D = clean(raw.O.T*s.Matrix.hstack(*(T*phi for T in raw.rhob)))
    F, free = D.T.gauss_jordan_solve(s.eye(9)); assert free.rows == 0
    F = rational(F); eq(D.T*F, s.eye(9))
    normal = rational(-raw.O*F)
    vectors = clean(s.Matrix.vstack(*((T*y).T for T in raw.Tb)))
    a = rational(raw.Rd.row_join(s.zeros(70, 36))+normal*vectors)
    metric = rational(s.Abs(e.det())*(e.T*ETA*e).inv())
    h00 = metric[0, 0]; assert h00 < 0
    U = [sum((A[i, k]*raw.rho[k]*phi for k in range(12)), s.zeros(70, 1)) for i in range(3)]
    b = clean(sum((metric[0, i+1]*U[i] for i in range(3)), s.zeros(70, 1)))
    db = s.zeros(70, 97)
    for i in range(3):
        RA = sum((A[i, k]*raw.rho[k] for k in range(12)), s.zeros(70))
        db[:, :61] += metric[0, i+1]*RA*raw.R
        for k in range(12): db[:, 61+12*i+k] = metric[0, i+1]*raw.rho[k]*phi
    potential = s.cancel(-sum(metric[i+1, j+1]*(U[i].T*U[j])[0]/2 for i in range(3) for j in range(3))+
                         s.Abs(e.det())*((phi-raw.v).T*(phi-raw.v))[0])
    divergence = s.zeros(70, 1); drift = s.zeros(1, 97); dc = s.zeros(1, 9)
    div_principal = s.zeros(97, 1); div_mixed = s.zeros(9, 1)
    div_shift = s.S.Zero
    derivatives = []
    for u in range(97):
        dD = (raw.O.T*s.Matrix.hstack(*(T*raw.R[:, u] for T in raw.rhob))
              if u < 61 else s.zeros(9))
        if dD.todok():
            dF, free = D.T.gauss_jordan_solve(-dD.T*F); assert free.rows == 0
            dF = rational(dF)
        else: dF = s.zeros(9)
        eq(dD.T*F+D.T*dF, s.zeros(9))
        dn = rational(-raw.O*dF)
        dV = s.Matrix.vstack(*(T[:, u].T for T in raw.Tb))
        da = rational(dn*vectors+normal*dV)
        divergence += da[:, u]
        drift += a[:, u].T*da
        dc += a[:, u].T*dn
        # Direct divergence of the complete second-order/current tensors.
        div_principal += da.T*a[:, u]+a.T*da[:, u]
        div_mixed += dn.T*a[:, u]+normal.T*da[:, u]
        div_shift += (da[:, u].T*b+a[:, u].T*db[:, u])[0]
        derivatives.append((da, dn))
    divergence, drift, dc = map(rational, (divergence, drift, dc))
    principal = rational(a.T*a); mixed = rational(a.T*normal)
    eq(rational(div_principal), drift.T+a.T*divergence)
    eq(rational(div_mixed), dc.T+normal.T*divergence)
    zero(div_shift-(divergence.T*b)[0]-sum(a[i, u]*db[i, u] for i in range(70) for u in range(97)))
    eq(principal.T, principal); eq(principal.conjugate(), principal)
    eq(mixed.conjugate(), mixed)
    normal_square = rational(normal.T*normal)
    eq(normal_square.T, normal_square); eq(normal_square.conjugate(), normal_square)
    for Q, T in zip(raw.Qb, raw.Tb): eq(Q.H, Q); zero(s.trace(T))
    return dict(phi=phi, D=D, F=F, a=a, normal=normal, b=b, db=db, h00=h00,
        potential=potential, Q=raw.Qb, drift=drift, dc=dc, divergence=divergence,
        div_principal=rational(div_principal), div_mixed=rational(div_mixed),
        div_shift=s.cancel(div_shift), principal=principal, mixed=mixed,
        normal_square=normal_square, derivatives=derivatives)


def form_action(data, word, value, gradient, Hessian):
    """Divergence-form coefficients, independently of old-square+correction."""
    unit = {word: 1}; h = 2*data['h00']
    charges = [current(Q, unit) for Q in data['Q']]
    principal = data['principal']
    scalar = -sum(v*Hessian[i, j] for (i, j), v in principal.todok().items())
    scalar -= (data['div_principal'].T*gradient)[0]
    scalar += 2*s.I*(data['b'].T*data['a']*gradient)[0]
    scalar += value*(s.I*data['div_shift']+(data['b'].T*data['b'])[0])
    coefficient = -2*s.I*gradient.T*data['mixed']-s.I*value*data['div_mixed'].T
    coefficient -= 2*value*data['b'].T*data['normal']
    return terms([(s.cancel(scalar/h+value*data['potential']), unit)]+
        [(coefficient[j]/h, charges[j]) for j in range(9)]+
        [(value*c/h, current(data['Q'][i], charges[j])) for (i, j), c in data['normal_square'].todok().items()])


def adjoint_difference(data, word, value, gradient):
    r = data['divergence']; h = 2*data['h00']; unit = {word: 1}
    scalar = -(r.T*data['a']*gradient)[0]+s.I*value*(r.T*data['b'])[0]
    current_coefficients = -s.I*value*r.T*data['normal']
    return terms([(scalar/h, unit)]+
        [(current_coefficients[j]/h, current(data['Q'][j], unit)) for j in range(9)])


def second_class_measure(raw, saved):
    W = raw.B.row_join(raw.S); Wi = W.inv()
    structures = [clean(Wi*sum((W[k, a]*raw.ad[k] for k in range(12)), s.zeros(12))*W)
                  for a in range(9)]
    currents = s.Matrix(s.symbols('actual_G0:12', real=True))
    bracket = s.Matrix(9, 9, lambda a, b: sum(structures[a][k, b]*currents[k] for k in range(12)))
    eq(bracket.T, -bracket)
    gram = raw.O.T*raw.O
    frame = raw.R.row_join(raw.O); dual = raw.Rd.row_join(raw.O*gram.inv())
    eq(frame.T*dual, s.eye(70)); eq(dual*frame.T, s.eye(70))
    answers = []
    for name, phi in [('source_second_class_measure', raw.v),
                      ('live_second_class_measure', raw.v+raw.R*(raw.Rd.T*raw.v)/100)]:
        record = saved[name]
        D = clean(raw.O.T*s.Matrix.hstack(*(T*phi for T in raw.rhob)))
        eq(D, decode(record['D9']))
        eq(bracket, decode(record['actual_broken_Gauss_bracket'], {str(x): x for x in currents}))
        Delta = s.zeros(9).row_join(D).col_join((-D.T).row_join(bracket))
        inverse, free = Delta.gauss_jordan_solve(s.eye(18)); assert free.rows == 0
        eq(Delta*inverse, s.eye(18)); eq(inverse*Delta, s.eye(18))
        eq(inverse, decode(record['Dirac_inverse'], {str(x): x for x in currents}))
        # Swapping the block rows makes Delta block triangular; its determinant
        # is det(D)^2 for every skew bracket, including nonzero residual Gauss.
        permutation = s.zeros(9).row_join(s.eye(9)).col_join(s.eye(9).row_join(s.zeros(9)))
        triangular = permutation*Delta
        eq(triangular[:9, 9:], bracket); eq(triangular[9:, :9], s.zeros(9))
        determinant = s.factor(D.det())
        zero(-triangular[:9, :9].det()*triangular[9:, 9:].det()-determinant**2)
        derivative = D.T*gram.inv()
        eq(derivative, decode(record['normal_Gauss_momentum_Jacobian']))
        cancellation = s.simplify(abs(determinant)/(abs(gram.det())*abs(derivative.det())))
        assert cancellation == 1
        answers.append({'point': name, 'Dirac_determinant': str(determinant**2),
            'canonical_phase_measure_cancellation': str(cancellation)})
    return answers


