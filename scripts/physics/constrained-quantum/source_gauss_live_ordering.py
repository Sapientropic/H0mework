#!/usr/bin/env python3
"""Live coefficient commutators in the source Gauss momentum square.

The ordered normal momentum is generated by D(phi)^T zeta = -G_base.
Its square retains the derivative of D(phi)^(-T) under the scalar CCR
current. Coefficients are never moved past that current without the original
commutator. This is a local reduced operator identity, not an evolution or
a choice of a completed quantum Hilbert domain.
"""
from __future__ import annotations

import hashlib
import json
import time

import sympy as s

from dynamic import HERE, ROOT, ROOT_ID
from source_scalar_gauss_reduction import SourceScalarGaussReduction
from source_lorentz_contact import clean, equal, encode


class SourceGaussLiveOrdering:
    def __init__(self):
        self.graph = SourceScalarGaussReduction()
        self.c = self.graph.constraints
        self.rho = [self.c.rho[j] for j in self.c.broken_columns]
        self.gram = self.c.gram
        self.normal_dual = self.graph.O*self.gram.inv()
        self.compressed = [clean(self.graph.dual_R.T*T*self.graph.R) for T in self.rho]
        for T in self.c.rho:
            # The original Pi.rho.phi has no hidden divergence constant in
            # either the fixed tangential or the normal coordinate block.
            assert s.trace(self.graph.dual_R.T*T*self.graph.R) == 0
            assert s.trace(self.normal_dual.T*T*self.graph.O) == 0

    def coefficients(self, e, x):
        phi = clean(self.c.vacuum+self.graph.R*x)
        D = clean(self.c.select.T*self.c.consistency_matrix(phi)*self.c.select)
        assert D.det() != 0
        F = clean(D.T.inv())
        b = [clean(self.graph.dual_R.T*T*phi) for T in self.rho]
        directional_D = [clean(self.c.select.T*self.c.consistency_matrix(self.graph.R*v)*self.c.select) for v in b]
        directional_F = [clean(-F*dD.T*F) for dD in directional_D]
        h00 = self.c.metric_density(e)[0][0, 0]
        K = clean(F.T*self.gram*F/(2*h00))
        correction = clean(-s.I*sum((F[:, a].T*self.gram*directional_F[a]
                                      for a in range(9)), s.zeros(1, 9))/(2*h00))
        return {'phi': phi, 'D': D, 'F': F, 'scalar_vectors': b,
                'directional_D': directional_D, 'directional_F': directional_F,
                'h00': h00, 'quadratic': K, 'linear': correction}


def main():
    started = time.monotonic()
    model = SourceGaussLiveOrdering()
    background = model.graph.common.scalar.exchange.active['actual_background']
    e = s.Matrix(background['coframe']).applyfunc(s.sympify)
    at_source = model.coefficients(e, s.zeros(61, 1))
    equal(at_source['linear'], s.zeros(1, 9))
    equal(at_source['quadratic'], -e[0, 0]*model.gram.inv()/2)
    x = s.Matrix([s.Rational((3*j+1) % 7-3, 100) for j in range(61)])
    data = model.coefficients(e, x)
    # Independently differentiate each complete inverse along the actual
    # 61-coordinate current direction, freezing that tangent at the point.
    t = s.Symbol('curve_parameter', real=True)
    for a in range(9):
        Dcurve = data['D']+t*data['directional_D'][a]
        direct = Dcurve.T.inv().diff(t).subs(t, 0)
        equal(direct, data['directional_F'][a])
    assert data['linear'].todok()
    assert s.simplify(sum(s.conjugate(v)*v for v in data['linear'])) != 0
    equal(data['D'].T*data['F'], s.eye(9))
    # Extract the first-order coefficient directly from the nested zeta
    # operators. This preserves all nine ordered currents G_c G_d.
    direct_linear = s.zeros(1, 9)
    for a, b in model.gram.todok():
        for c in range(9):
            direct_linear += (-s.I*model.gram[a, b]*data['F'][a, c]*
                              data['directional_F'][c][b, :]/(2*data['h00']))
    equal(clean(direct_linear), data['linear'])
    print('PASS live source inverse derivatives and nonzero Gauss scalar-current ordering correction', flush=True)
    paths = [HERE/name for name in ('source_gauss_live_ordering.py', 'source_scalar_gauss_reduction.py',
        'source_scalar_gauss_reduction.json', 'independent_source_scalar_gauss_reduction.json',
        'source_gauss_quantum_current.py', 'source_gauss_quantum_current.json',
        'source_constraint_preservation.py')]
    result = {'root': ROOT_ID, 'source_sha256': model.graph.common.scalar.exchange.vertices['source_sha256'],
        'input_sha256': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths},
        'scope': 'LIVE_SOURCE_GAUSS_NORMAL_MOMENTUM_SQUARE_ORDERED_COEFFICIENT_IDENTITY',
        'original_current': 'G_a=B_a+J_a, B_scalar,a=-i b_a(x).partial_x, b_a=Rdual^T rho_a(v+R*x); the other factors commute with F(x)',
        'normal_equation': 'D(phi)^T zeta=-G; zeta=-F(x)G, F=D(phi)^(-T)',
        'energy': 'sum_ab Gram_ab*zeta_a*zeta_b/(2h00)=sum_cd K_cd*G_c*G_d+sum_d L_d*G_d',
        'quadratic_coefficient': 'K=F^T Gram F/(2h00)',
        'linear_coefficient': 'L=-i sum_c F[:,c]^T Gram (b_c.partial_x F)/(2h00)',
        'complete_current_order_preserved': True,
        'all12_tangent_and_normal_current_divergence_constants_zero': True,
        'source_linear_correction_zero': True,
        'actual_off_source_scalar_coordinates': encode(x),
        'actual_off_source_quadratic_coefficient': encode(data['quadratic']),
        'actual_off_source_linear_coefficient': encode(data['linear']),
        'omitting_coefficient_current_commutator_changes_operator': True,
        'all9_inverse_derivatives_directly_recomputed': True,
        'completed_quantum_domain_adjoint_evolution_or_spectrum_claimed': False,
        'lifetime_status': 'SOURCE_NATIVE_DYNAMIC_MEASURE_REQUIRED',
        'elapsed_seconds': round(time.monotonic()-started, 3)}
    (HERE/'source_gauss_live_ordering.json').write_text(json.dumps(result, indent=2)+'\n')


if __name__ == '__main__':
    main()
