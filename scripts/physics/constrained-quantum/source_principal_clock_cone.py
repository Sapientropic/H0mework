def zero(value): assert s.factor(s.cancel(value)) == 0


def positive_minors(matrix):
    values=[s.factor(matrix[:j,:j].det()) for j in range(1,matrix.rows+1)]
    assert all(v>0 for v in values)
    return list(map(str,values))


