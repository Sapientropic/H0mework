    Pi,E,S=model.gram(f,p)
    electric=E/2
    scalar_trace=s.factor(s.trace(v*qq.inv().T*electric*qq.inv()))
    zero(sum(q[j]*s.diff(scalar_trace,q[j]) for j in range(6))-scalar_trace)
    radius=s.sqrt(v); dr=s.Matrix([s.diff(radius,x) for x in q])
