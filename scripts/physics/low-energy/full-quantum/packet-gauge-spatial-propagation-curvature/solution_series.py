#!/usr/bin/env python3
"""Same-root analytic forcing and original source solution, before taking norms."""
from fractions import Fraction as F
from functools import lru_cache
from math import factorial, isqrt
import importlib.util
import json
from pathlib import Path
import sys
import time
import sympy as s

sys.dont_write_bytecode = True
sys.set_int_max_str_digits(0)
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('source_solution_interval_matrix', HERE/'inverse_series.py')
inv = importlib.util.module_from_spec(spec); spec.loader.exec_module(inv)
source, FQ, BASE = inv.source, inv.FQ, inv.BASE
Ball, UNIT, imatrix = inv.Ball, inv.UNIT, inv.imatrix
ORDER = 36
q, U, T = s.symbols('q U T', real=True)


def read(path): return json.loads(path.read_bytes())
def clean(M): return source.clean(M)


@lru_cache(None)
def real_interval(expression):
    part = s.expand(expression); lo = hi = F(0)
    for number in [30, 15, 2]:
        radical = s.sqrt(number); a = part.coeff(radical)
        assert a.is_Rational
        coefficient = F(str(a)); root = isqrt(number*UNIT*UNIT)
        ends = [coefficient*F(root, UNIT), coefficient*F(root+1, UNIT)]
        lo += min(ends); hi += max(ends); part = s.expand(part-a*radical)
    assert part.is_Rational
    return lo+F(str(part)), hi+F(str(part))


def algebraic_ball(M):
    real, imag, radius = [[[0]*M.cols for _ in range(M.rows)] for _ in range(3)]
    for (i, j), value in s.SparseMatrix(M).todok().items():
        rad = 0
        for array, part in zip([real, imag], [s.re(value), s.im(value)]):
            lo, hi = real_interval(part)
            low = lo.numerator*UNIT//lo.denominator
            high = -((-hi.numerator*UNIT)//hi.denominator)
            center = (low+high)//2
            array[i][j] = center; rad = max(rad, center-low, high-center)
        radius[i][j] = rad
    return Ball(imatrix(real), imatrix(imag), imatrix(radius))


@lru_cache(None)
def scalar_parts(value):
    v = s.QQ_I.to_sympy(value) if not isinstance(value, F) else s.Rational(value.numerator, value.denominator)
    parts = [F(str(s.re(v))), F(str(s.im(v)))]
    center = [a.numerator*UNIT//a.denominator for a in parts]
    return center[0], center[1], 1


def scale(M, value):
    ar, ai, error = scalar_parts(value)
    re, im = ar*M.re-ai*M.im, ar*M.im+ai*M.re
    rad = (abs(ar)+abs(ai))*M.rad+error*(inv.magnitude(M.re)+inv.magnitude(M.im))+2*error*M.rad
    arrays = [[[0]*M.re.ncols() for _ in range(M.re.nrows())] for _ in range(3)]
    for i in range(M.re.nrows()):
        for j in range(M.re.ncols()):
            arrays[0][i][j] = int(re[i, j])//UNIT
            arrays[1][i][j] = int(im[i, j])//UNIT
            arrays[2][i][j] = (int(rad[i, j])+UNIT-1)//UNIT+1
    return Ball(*map(imatrix, arrays))


def zero(n, m): return Ball(imatrix([[0]*m for _ in range(n)]))
def entry_norm(M):
    return F(max(abs(int(M.re[i, j]))+abs(int(M.im[i, j]))+2*int(M.rad[i, j])
                 for i in range(M.re.nrows()) for j in range(M.re.ncols())), UNIT)


def convolution(a, b, length):
    return [sum((a[j]*b[n-j] for j in range(n+1)), a[0]*0) for n in range(length)]


def powers(a, degree, length):
    result = [a[0]*0+1]+[a[0]*0]*(length-1)
    for _ in range(degree): result = convolution(result, a, length)
    return result


def main():
    began = time.monotonic()
    kernel = read(HERE/'kernel.json'); glob = read(FQ/'packet-gauge-global-transfer/source.json')
    upper = read(HERE/'inverse-series.json')
    R = F(upper['actual_source_circle_radius']); eps = F(upper['whole_original_light_radius_q'])
    gap = 1-F(upper['source_Neumann_theta'])
    z = s.sympify(kernel['physical_frequency']); c = s.sympify(glob['physical_clock'])
    Fbar = s.Poly(s.sympify(glob['complete_Fhat'], locals={'U': U, 'T': T})/s.sympify(glob['source_coefficient']), U, T)
    assert Fbar.nth(0, 0) == 0 and Fbar.nth(1, 0) == 1
    D = Fbar.diff(U)
    r, w = s.symbols('r w', real=True)
    remainder = s.Poly(s.sympify(glob['source_root_remainder'], locals={'r': r, 'w': w}), r, w)
    center = s.Rational(125, 162)
    assert s.expand(Fbar.as_expr().subs(U, T*r)-T*(r-center+T*remainder.as_expr().subs(w, T))) == 0
    root_bounds = [sum(abs(F(str(a)))*R**(2*j) for (i, j), a in P.terms()) for P in [remainder, remainder.diff(r)]]
    assert R*R*root_bounds[0] < F(1, 20) and R*R*root_bounds[1] < 1
    assert F(125, 162)+F(1, 20) < 1
    d_error = sum(abs(F(str(a)))*R**(2*(i+j)) for (i, j), a in (D-s.Poly(1, U, T)).terms())
    den_lower = (1-d_error)*(F(str(s.expand(z*s.conjugate(z))))-F(str(c*c))*R*R)
    assert den_lower > 0
    # Formal coefficients are generated by the original implicit polynomial,
    # whose coefficient of the next U term is exactly one.
    nT = ORDER//2
    uT = [F(0)]*(nT+1)
    terms = [(i, j, F(str(a))) for (i, j), a in Fbar.terms()]
    for n in range(1, nT+1):
        power = {i: powers(uT[:n+1], i, n+1) for i in {i for i, j, a in terms}}
        coefficient = sum(a*power[i][n-j] for i, j, a in terms if j <= n)
        uT[n] = -coefficient
    assert uT[1] == F(125, 162)
    us = [F(0)]*(ORDER+1)
    for n, value in enumerate(uT): us[2*n] = value
    upowers = {i: powers(us, i, ORDER+1) for i in range(12)}
    denominator = s.Poly(s.sympify(kernel['same_source_common_denominator'], locals={'q': q, 'U': U}), q, U, domain=s.QQ_I)
    den_series = [s.QQ_I.zero]*(ORDER+1)
    for (a, b), v in denominator.terms():
        v = s.QQ_I.from_sympy(v)
        for n in range(a, ORDER+1): den_series[n] += v*s.QQ_I.convert(s.Rational(upowers[b][n-a].numerator, upowers[b][n-a].denominator))
    reciprocal = [s.QQ_I.one/den_series[0]]
    for n in range(1, ORDER+1):
        reciprocal.append(-sum((den_series[j]*reciprocal[n-j] for j in range(1, n+1)), s.QQ_I.zero)/den_series[0])
    monomial_scalars = {}
    def scalar_series(a, b):
        key = (a, b)
        if key not in monomial_scalars:
            polynomial = [s.QQ_I.convert(s.Rational(v.numerator, v.denominator)) for v in upowers[b]]
            product = convolution(polynomial, reciprocal, ORDER+1)
            monomial_scalars[key] = [s.QQ_I.zero]*a+product[:ORDER+1-a]
        return monomial_scalars[key]
    forces = {tuple(beta): source.native.matrix(rec, {'q': q, 'U': U}) for beta, rec in kernel['normalized_force_jets']}
    operators = {tuple(beta): source.native.matrix(rec, {'q': q}) for beta, rec in kernel['normalized_operator_jets']}
    indices = sorted(forces, key=lambda a: (sum(a), a)); beta0 = (0, 0, 0)
    P, blocks = source.native.rational_inverse(clean(operators[beta0].subs(q, 0)))
    coefficients = {}
    for beta, matrix in operators.items():
        for degree in range(3):
            if beta == beta0 and degree == 0: continue
            M = s.SparseMatrix(112, 112, {(i, j): s.Poly(v, q).nth(degree) for (i, j), v in matrix.todok().items() if s.Poly(v, q).nth(degree)})
            if M.todok(): coefficients[beta, degree] = clean(P*M)
    Kballs = {a: algebraic_ball(M) for a, M in coefficients.items()}
    def matrix_contour(M):
        values = []
        for value in M.todok().values():
            bound = F(0)
            for (n, j), v in s.Poly(value, q, U).terms():
                absolute = sum(max(abs(a), abs(b)) for a, b in [real_interval(s.re(v)), real_interval(s.im(v))])
                bound += absolute*R**(n+2*j)
            values.append(bound)
        return max(values, default=F(0))
    transformed = {beta: clean(P*M) for beta, M in forces.items()}
    source_contour = {beta: matrix_contour(M)/den_lower for beta, M in transformed.items()}
    relative_contour = {beta: sum(inv.norm_exact(M)*R**degree for (b, degree), M in coefficients.items() if b == beta)
                        for beta in indices if beta != beta0}
    solution, contour, norms = {}, {}, {}
    def below(a): return [b for b in indices if all(x <= y for x, y in zip(b, a))]
    def sub(a, b): return tuple(x-y for x, y in zip(a, b))
    def choose(a, b): return int(s.prod(s.binomial(x, y) for x, y in zip(a, b)))
    for beta in indices:
        M = transformed[beta]
        by_monomial = {}
        for (i, j), value in M.todok().items():
            for powers_, v in s.Poly(value, q, U).terms():
                by_monomial.setdefault(powers_, s.MutableSparseMatrix(112, 9, {}))[i, j] = v
        monomials = [(algebraic_ball(M), scalar_series(*a)) for a, M in by_monomial.items()]
        solution[beta], norms[beta] = [], []
        for n in range(ORDER+1):
            value = zero(112, 9)
            for M, scalars in monomials:
                if scalars[n]: value += scale(M, scalars[n])
            for (gamma, j), M in Kballs.items():
                if j <= n and all(a <= b for a, b in zip(gamma, beta)):
                    term = M.mul(solution[sub(beta, gamma)][n-j])
                    value += -scale(term, F(choose(beta, gamma)))
            solution[beta].append(value); norms[beta].append(entry_norm(value))
        contour[beta] = (source_contour[beta]+sum(F(choose(beta, gamma))*relative_contour[gamma]*contour[sub(beta, gamma)]
                        for gamma in below(beta) if gamma != beta0))/gap
        print('PASS actual source vector series', beta, ORDER, flush=True)
    bounds = []
    t = eps/R
    for beta in indices:
        for a in range(5-sum(beta)):
            prefix = sum(norms[beta][n]*F(factorial(n), factorial(n-a))*eps**(n-a) for n in range(a, ORDER+1))
            tail = contour[beta]*(ORDER+1)**a*factorial(a)*t**(ORDER+1-a)/(R**a*(1-t)**(a+1))
            bounds.append({'external_multiindex': list(beta), 'radial_order': a,
                          'normalized_q_source_solution_derivative': str(prefix+tail),
                          'finite_source_series': str(prefix), 'true_analytic_tail': str(tail)})
    report = {'scope': 'SAME_ROOT_ACTUAL_SOURCE_SOLUTION_UNIFORM_MIXED_DERIVATIVE_BOUNDS',
              'physical_frequency': str(z), 'actual_q_circle': str(R), 'light_q_radius': str(eps),
              'root_complex_fixed_point_image': str(R*R*root_bounds[0]),
              'root_complex_fixed_point_contraction': str(R*R*root_bounds[1]),
              'source_denominator_circle_lower': str(den_lower),
              'root_U_T_coefficients': list(map(str, uT)), 'series_order_q': ORDER,
              'actual_source_contour_bounds': [[list(a), str(v)] for a, v in contour.items()],
              'uniform_derivatives': bounds, 'same_Noether_source_before_field': True,
              'dyadic_precision_bits': inv.PRECISION, 'seconds': round(time.monotonic()-began, 3)}
    (HERE/'solution-series.json').write_text(json.dumps(report, separators=(',', ':'))+'\n')
    print('PASS actual source solution mixed bounds',
          [(v['external_multiindex'], v['radial_order'], float(F(v['normalized_q_source_solution_derivative']))) for v in bounds],
          report['seconds'], flush=True)


if __name__ == '__main__': main()
