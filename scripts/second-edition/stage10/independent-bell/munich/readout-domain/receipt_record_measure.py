    def _box_cells(self, rows, domains):
        _, _, reasons = self._restriction(rows)
        if reasons:
            return None, None, [], reasons
        inner, outer, certificates = [], [], []
        rate = 1000*self._writer.seconds_per_unit
        for side, (row, encoder, event, domain) in enumerate(zip(rows, self._writer.encoders, self._events, domains)):
            uid = history.schema.integer(row[4], 'local_timestamp')
            n = (uid-encoder.uid_origin)//encoder.uid_stride
            unix = history.schema.timestamp(row[1], 'Unix-time')
            constraints = (
                ('UID ceil', (n-1, 1, 0, -1, 0), -event['RN_request'],
                             (n, 1, 0, -1, 0), -event['RN_request'], False, True),
                ('RN age', (n, 1, 0, 0, 0), -event['RN_output'],
                           (n, 1, 0, 0, 0), -event['earliest_RN_correlation'], True, True),
                ('Unix floor', (0, 0, -1/rate, 0, -1), unix/rate-event['CEM_logic_deadline'],
                               (0, 0, -1/rate, 0, -1), (unix+1)/rate-event['CEM_logic_deadline'], True, False))
            for name, lc, a, uc, b, closed_l, closed_u in constraints:
                ll, lu = _affine_range(domain, lc, a)
                ul, uu = _affine_range(domain, uc, b)
                inner.append(clock.Interval(lu, ul, closed_l, closed_u))
                outer.append(clock.Interval(ll, uu, closed_l, closed_u))
                certificates.append({'side': side, 'source_constraint': name,
                    'lower_affine_range': list(map(str, (ll, lu))), 'upper_affine_range': list(map(str, (ul, uu))),
                    'lower_closed': closed_l, 'upper_closed': closed_u})
        return _intersection(inner), _intersection(outer), certificates, reasons

