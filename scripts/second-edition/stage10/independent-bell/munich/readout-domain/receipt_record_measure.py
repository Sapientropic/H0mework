    def _joint_state(self, roles, carriers, domain, clicks, command, common_error, tail):
        inner, shell, outer = (roles[name] for name in ('inner', 'shell', 'outer'))
        inner_carrier, shell_carrier = carriers['inner'], carriers['shell']
        channel._require(all(type(item) is detector_family.WindowDetectorFamily and
                             item.record() == inner_carrier.record() for item in carriers.values()),
                         'every time restriction must use the same complete detector source')
        envelope = inner['detector_envelope_without_common_error']
        aa = tuple(tuple(map(Q, row)) for row in envelope['q_A_simplex_box_vertices'])
        bb = tuple(tuple(map(Q, row)) for row in envelope['q_B_simplex_box_vertices'])
        noises = tuple(tuple(map(Q, row)) for row in envelope['background_box_endpoints'])
        a0 = tuple(sum((row[i] for row in aa), Q(0))/len(aa) for i in range(4))
        b0 = tuple(sum((row[i] for row in bb), Q(0))/len(bb) for i in range(4))
        n0 = tuple((min(row[i] for row in noises)+max(row[i] for row in noises))/2 for i in range(2))
        vi = inner_carrier.vertex_states(inner['family_report'])
        vs = shell_carrier.vertex_states(shell['family_report'])
        weights0 = fibre._weights(a0, b0, n0)
        groups = {}
        for a,b,bg in product(range(4), range(4), detector_family.BACKGROUND_VERTICES):
            selected = fibre._selected(detector_family._noise(vi[a,b]['state'], bg), clicks)
            key = channel._canonical(channel._input_record(selected))
            group = groups.setdefault(key, {'members': [], 'norm': projected.bsm._entry_norm(selected)})
            group['members'].append((a,b,bg))
        local_joint = max(sum((a[i]*b[j]*(vi[i,j]['local_error']+vs[i,j]['local_error'])
                               for i,j in detector_family.PARAMETERS), Q(0)) for a,b in product(aa,bb))
        variation, shell_mass = Q(0), Q(0)
        for a,b,bg in product(aa,bb,noises):
            weights = fibre._weights(a,b,bg)
            # Equal generated full matrices can share their coefficient sum;
            # the primitive source vertices and all local error prices remain.
            variation = max(variation, sum((abs(sum((weights[key]-weights0[key]
                                 for key in group['members']), Q(0)))*group['norm']
                                 for group in groups.values()), Q(0)))
            value = shell_carrier.evaluate(shell['family_report'],a,b,bg)
            mass, rounding = detector_family._trace(fibre._selected(value['state'], clicks))
            shell_mass = max(shell_mass, mass+rounding)
        joint_error = common_error+local_joint+command
        row = next(row for row in envelope['outcomes'] if tuple(row['clicks']) == clicks)
        lower = max(Q(0), Q(row['unnormalized_mass_bounds'][0])-common_error-command)
        upper_row = next(row for row in outer['detector_envelope_without_common_error']['outcomes']
                         if tuple(row['clicks']) == clicks)
        total_upper = max(Q(0), Q(upper_row['unnormalized_mass_bounds'][1])+common_error+command+tail)
        centre = inner_carrier.evaluate(inner['family_report'], a0,b0,n0)
        selected = fibre._selected(centre['state'],clicks)
        mass, rounding = detector_family._trace(selected)
        base = {'schema': 'stage10-joint-record-live-parameter-normalized-state/v1',
            'live_parameter_domain': {'encoder_reference': 'encoder_domains', 'detector': domain},
            'observed_event_mass_bounds': list(map(str, (lower, total_upper))),
            'parameter_domain_removed': False, 'zero_likelihood_fibres_have_no_posterior': True,
            'input_positive_source_required': True, 'hardware_prior_used': False,
            'normalized_vertex_average_used': False, 'common_time_error': str(common_error),
            'max_same_theta_inner_plus_shell_local_error': str(local_joint),
            'whole_outer_command_substitution_payment': str(command),
            'joint_numeric_error_budget': str(joint_error),
            'detector_parameter_variation_entry_norm_upper': str(variation),
            'generated_equal_matrix_coefficient_groups': len(groups),
            'positive_shell_center_mass_upper_without_common_error': str(shell_mass),
            'positive_outer_selected_tail_upper': str(tail),
            'normalization_centre_parameter': {'q_A': list(map(str,a0)), 'q_B': list(map(str,b0)),
                                              'backgrounds': list(map(str,n0)), 'actual_hardware_value_selected': False},
            'unnormalized_centre': channel._input_record(selected), 'normalizer_centre': str(mass),
            'common_error_repeated_per_vertex_or_endpoint': False,
            'error_allocation': 'one disjoint inner/shell CP instrument; move shell numeric error to the larger inner normalization sensitivity'}
        if lower <= 0 or mass <= 0:
            return {**base, 'status': 'joint_parameter_domain_event_normalizer_unresolved',
                    'normalized_state_box_generated': False}
        norm = projected.bsm._entry_norm(selected)
        sensitivity = max(Q(2), 1+norm/mass)
        epsilon = joint_error+variation+rounding
        remainder = shell_mass+tail
        price = sensitivity*epsilon/lower+2*remainder/(lower+remainder)
        return {**base, 'status': 'joint_parameter_domain_normalized_state_generated',
            'uniform_inner_error_after_joint_allocation': str(epsilon),
            'normalization_sensitivity': str(sensitivity),
            'positive_remainder_mass_upper_without_repeated_numeric_error': str(remainder),
            'normalized_complete_state_centre': channel._input_record({key:value*(1/mass) for key,value in selected.items()}),
            'uniform_posterior_trace_norm_error': str(price), 'normalized_state_box_generated': True,
            'bound': 'A*(jointE+variation+trace-rounding)/nl + 2*(shell-center-upper+tail)/(nl+shell-center-upper+tail), A=max(2,1+norm(C0)/m0)'}

