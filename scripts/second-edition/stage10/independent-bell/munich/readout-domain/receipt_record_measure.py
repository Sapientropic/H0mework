def _copy(value):
    return projected._copy(value)


def _closed(value):
    for base in type(value).__mro__:
        for name, method in vars(base).items():
            if callable(method) or isinstance(method, (classmethod, staticmethod, property)):
                channel._require(name not in vars(value), 'source operations cannot be instance callbacks')


def _law_record(law):
    return {'certificate': law.certificate, 'start_time': str(law.start_time),
            'inherited_error': str(law.inherited_error)}


def _components(mother):
    return mother.components if type(mother) is all_ready.AllReadyHistoryLaw else (mother,)


def _inventory(mother):
    return [[_law_record(law) for law in item.programme.first_receipt_laws]
            for item in _components(mother)]


def _bindings():
    modules = (all_ready, component, projected, response, writer, stopped, window, clock,
               observed, history, channel, full, detector_family, fibre)
    paths = {Path(__file__).resolve(), *(Path(module.__file__).resolve() for module in modules)}
    return [{'path': str(path.relative_to(full.ROOT)),
             'sha256': hashlib.sha256(path.read_bytes()).hexdigest()} for path in sorted(paths)]


def _shift(item, offset):
    return None if item is None else clock.Interval(item.lower+offset, item.upper+offset,
                                                   item.lower_closed, item.upper_closed)


def _intersection(items):
    return None if any(item is None for item in items) else clock.intersect(tuple(items))


def _interval(item):
    return clock._interval_record(item)


def _lead_time(raw):
    # These are original raw pair phases executed before the next BSM gate.
    elapsed = Q(0)
    for name in ('preparation', 'excitation', 'arrival_delay_phases'):
        for phase in raw[name]:
            segments = tuple(full.Segment.from_record(item) for item in phase['raw_segments'])
            channel._require(len(segments) == 2 and segments[0].duration == segments[1].duration,
                             'original common pair-phase clock required')
            elapsed += segments[0].duration
    return elapsed


def _time_price(mother):
    return (mother.global_time_error if type(mother) is all_ready.AllReadyHistoryLaw else
            mother.programme.global_time_error)


def _function_signature(value):
    value = getattr(value, '__func__', value)
    return id(value), id(getattr(value, '__code__', None)), repr(getattr(value, '__defaults__', None)), repr(getattr(value, '__kwdefaults__', None))


def _encoder_domain(encoder, overrides):
    channel._require(type(overrides) is dict and set(overrides) <= set(TIME_FIELDS),
                     'raw encoder time-coordinate box required; labels and integer UID chart stay fixed')
    result = {}
    for name in TIME_FIELDS:
        pair = overrides.get(name, (getattr(encoder, name),)*2)
        channel._require(type(pair) in (tuple, list) and len(pair) == 2, 'exact lower/upper encoder coordinates required')
        lo, hi = map(full.exact, pair)
        channel._require(lo <= hi and (name != 'sample_period' or lo > 0) and
                         (name not in ('request_latency', 'write_latency') or lo >= 0),
                         'every encoder point must satisfy the original physical constructor')
        result[name] = [str(lo), str(hi)]
    return result


def _affine_range(domain, coefficients, constant):
    lower = upper = Q(constant)
    for name, coefficient in zip(TIME_FIELDS, coefficients):
        lo, hi = map(Q, domain[name])
        a, b = coefficient*lo, coefficient*hi
        lower += min(a, b)
        upper += max(a, b)
    return lower, upper


def _detector_domain(value):
    value = {'q_A': [[0, 1]]*4, 'q_B': [[0, 1]]*4, 'backgrounds': [[0, 1]]*2} if value is None else value
    channel._require(type(value) is dict and set(value) == {'q_A', 'q_B', 'backgrounds'},
                     'complete raw registration/background domain required')
    result = {}
    for name, size in (('q_A', 4), ('q_B', 4), ('backgrounds', 2)):
        channel._require(type(value[name]) in (tuple, list) and len(value[name]) == size,
                         'complete detector coordinate box required')
        rows = []
        for pair in value[name]:
            channel._require(type(pair) in (tuple, list) and len(pair) == 2, 'two exact detector bounds required')
            lo, hi = map(full.exact, pair)
            channel._require(0 <= lo <= hi <= 1, 'physical raw detector coordinates required')
            rows.append([str(lo), str(hi)])
        if size == 4:
            detector_family._simplex_box(rows)
        result[name] = rows
    return result


def _shell_cells(inner, outer):
    if outer is None:
        return ()
    if inner is None:
        return (outer,)
    channel._require(outer.lower <= inner.lower <= inner.upper <= outer.upper,
                     'source-generated inner cell must lie in its outer cell')
    candidates = (clock.Interval(outer.lower, inner.lower, outer.lower_closed, not inner.lower_closed),
                  clock.Interval(inner.upper, outer.upper, not inner.upper_closed, outer.upper_closed))
    return tuple(cell for value in candidates if (cell := clock.intersect((value,))) is not None)


def _herald_pinching(measure, herald):
    matrices = [projected.project(matrix, mask) for index, matrix in enumerate(measure['poststates'])
                if projected.bsm.PATTERNS[index][0] == herald for mask in projected.MASKS]
    return component._sum(matrices)


