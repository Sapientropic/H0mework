"""Full ready/receipt history -> all nominal-setting future CEM laws.

The four settings are generated from one raw measurement source before any
next outcome is selected.  Source normalization uses the same mother receipt
measure, while a selected posterior keeps its whole-event denominator.
"""
import copy
from fractions import Fraction as Q
from itertools import product

import atomic_dipole as dipole
import fluorescence_channel as channel
import history_prefix
import interval_prefix
import measurement_programme as measurement
import projected_window_cem as projected
import window_cem_source as window


SCHEMA = 'stage10-projected-full-history-CEM-law/v1'
SETTINGS = tuple(product((0, 1), repeat=2))
HERALDS = ('Psi+', 'Psi-')


def _sum(matrices):
    result = {}
    for matrix in matrices:
        projected._add(result, matrix)
    return result


def _selected(report, herald, clicks=None):
    result = {}
    for packet in report['packets']:
        if packet['physical_herald'] == herald:
            for (mark, i, j), value in window._read_marked(packet['complete_marked_matrix']).items():
                if clicks is None or mark.clicks == clicks:
                    projected._add(result, {(i, j): value})
    return result


def _price(programs, receipt):
    raw = sum((Q(item['cptp_duhamel_trace_norm_error']) for program in programs
               for item in program.hamiltonian_certificates), Q(0))
    mass, radical = projected._trace(_sum(receipt['poststates']))
    return raw*max(Q(0), mass+radical+receipt['global_trace_norm_error'])


class ProjectedHistoryLaw:
    def __init__(self, mother, measurement_source):
        channel._require(type(mother) is projected.ProjectedWindowCEM and
                         type(measurement_source) is measurement.PairMeasurementSource,
                         'closed ready/receipt mother and shared raw measurement source required')
        self._initialize(projected.ProjectedWindowCEM.from_record(copy.deepcopy(mother.record())),
                         measurement.PairMeasurementSource.from_record(measurement_source.record()))

    def _initialize(self, mother, measurement_source):
        self.mother, self.measurement = mother, measurement_source
        baseline = [[segment.record() for segment in side] for side in self.mother.source.waveforms]
        channel._require(any([[segment.record() for segment in program.segments] for program in
                              self.measurement.compile(settings)] == baseline for settings in SETTINGS),
                         'the original window waveform must be generated by the same shared control source')

    def source(self, settings):
        programs = self.measurement.compile(settings)
        base = self.mother.source
        channel._require(self.measurement.detector.backgrounds == base.backgrounds,
                         'same raw background must serve every nominal setting')
        raw = window.WindowCEMSource(*(program.segments for program in programs),
                  registrations=base.registrations, backgrounds=base.backgrounds,
                  logic_deadlines=base.logic_deadlines, seconds_per_unit=base.seconds_per_unit,
                  interval_start=base.interval_start)
        record = copy.deepcopy(self.mother.record())
        record['raw_window_source'] = raw.record()
        return projected.ProjectedWindowCEM.from_record(record)

    def record(self):
        return {'schema': SCHEMA, 'mother': self.mother.record(), 'raw_measurement': self.measurement.record(),
                'settings': [list(settings) for settings in SETTINGS],
                'raw_fragment_efficiency_reapplied': False,
                'source_domain': 'same complete mother state/time law, shared hardware, four generated commands',
                'receipt_scope': 'one source receipt component; complete hidden-attempt mixture belongs to the stopped source',
                'next_outcome_used_to_generate_prediction': False,
                'actual_hardware_uniquely_identified': False, 'controller_advance': False}

    def hardware_record(self):
        gate = copy.deepcopy(self.mother.invariance['raw_source'])
        for field in ('gate_start', 'gate_end', 'interval_start'):
            gate.pop(field)
        ingress = self.mother.burst_ingress
        burst = None if ingress is None else copy.deepcopy(ingress['raw_burst'])
        if burst is not None:
            for field in ('gate_start', 'gate_end', 'interval_start'):
                burst['gate'].pop(field)
        base = self.mother.source
        return {'raw_measurement': self.measurement.record(), 'raw_BSM_hardware': gate,
                'raw_burst_hardware': burst,
                'raw_reload': self.mother.parent_programme_record,
                'registration': [item.record() for item in base.registrations],
                'backgrounds': list(map(str, base.backgrounds)),
                'logic_deadlines': list(map(str, base.logic_deadlines)),
                'seconds_per_unit': str(base.seconds_per_unit)}

    @classmethod
    def from_record(cls, record):
        channel._require(type(record) is dict and record.get('schema') == SCHEMA, 'closed full-history law required')
        source = object.__new__(cls)
        source._initialize(projected.ProjectedWindowCEM.from_record(record['mother']),
                           measurement.PairMeasurementSource.from_record(record['raw_measurement']))
        channel._require(source.record() == record, 'full-history source or scope changed')
        return source

    def _assemble(self, reports):
        receipt = self.mother.law.interval()
        denominators = []
        for herald in HERALDS:
            state = _sum(matrix for index, matrix in enumerate(receipt['poststates'])
                         if projected.bsm.PATTERNS[index][0] == herald)
            mass, radical = projected._trace(state)
            error = receipt['global_trace_norm_error']+radical
            channel._require(mass-error > 0, 'whole-history physical herald normalizer is unresolved')
            denominators.append((mass, error))
        rows, payments = [], []
        for settings, report in zip(SETTINGS, reports):
            channel._require(tuple(map(Q, report['receipt_time_support'])) == self.mother.law.support,
                             'future prediction requires the whole mother receipt support')
            payment = _price(self.measurement.compile(settings), receipt)
            payments.append(str(payment))
            for h, herald in enumerate(HERALDS):
                denominator, denominator_error = denominators[h]
                error = Q(report['global_trace_norm_error'])+payment
                for clicks in window.REGISTRATION_ORDER:
                    state = _selected(report, herald, clicks)
                    mass, radical = projected._trace(state)
                    local_error = error+radical
                    low = max(Q(0), (mass-local_error)/(denominator+denominator_error))
                    high = min(Q(1), (mass+local_error)/(denominator-denominator_error))
                    channel._require(low <= high, 'source event enclosure misses a normalized probability')
                    rows.append({'h': h, 'a': settings[0], 'b': settings[1], 'x': clicks[0], 'y': clicks[1],
                                 'probability_interval': list(map(str, (low, high))),
                                 'joint_center': str(mass), 'joint_error': str(local_error)})
        rows.sort(key=lambda row: tuple(row[field] for field in ('h', 'a', 'b', 'x', 'y')))
        table = self._table(rows)
        return {'schema': SCHEMA, 'source_record': self.record(), 'setting_reports': reports,
                'source_probability_enclosures': rows, 'command_substitution_payments': payments,
                'whole_herald_normalizers': [{'center': str(m), 'error': str(e)} for m, e in denominators],
                'complete_contexts': len(table), 'all_outcomes_generated_before_observation': True,
                'source_quantum_time_law_retained': True, 'whole_upstream_error_paid_once': True,
                'nominal_command_error_paid_once_per_setting': True,
                'static_Bell_input_substituted': False, 'statistical_prefixes_executed': 0,
                'original_unconditioned_next_record_law_certified': False,
                'complete_record_clock_square_certified': False,
                'actual_hardware_uniquely_identified': False, 'controller_advance': False}

    @staticmethod
    def _table(rows):
        table = {context: [] for context in interval_prefix.CONTEXTS}
        for row in rows:
            table[row['h'], row['a'], row['b']].append(tuple(map(Q, row['probability_interval'])))
        return interval_prefix.probability_table(table)

    def forecast(self, *, taylor_order=6):
        return self._assemble([self.source(settings).interval(taylor_order=taylor_order) for settings in SETTINGS])

    def verify(self, report):
        channel._require(type(report) is dict and report.get('source_record') == self.record(),
                         'same full-history mother/control source required')
        channel._require(len(report['setting_reports']) == 4, 'all four generated nominal settings required')
        for settings, item in zip(SETTINGS, report['setting_reports']):
            self.source(settings).verify(item)
        channel._require(self._assemble(report['setting_reports']) == report, 'full-history probability law changed')
        return True

    def probability_table(self, report):
        self.verify(report)
        return self._table(report['source_probability_enclosures'])

    def seal_prediction(self, report, consumer, *, model_record):
        channel._require(type(consumer) in (history_prefix.HistoryPrefixChecker, history_prefix.HistoryPrefixes),
                         'original predictable full-history consumer required')
        channel._require(model_record == self.hardware_record(), 'prediction must retain its actual raw hardware model')
        table = self.probability_table(report)
        return consumer.predict(table, model_record=model_record,
                                parent_history={'complete_source': report['source_record'],
                                                'forecast_sha256': channel._digest(report)})
